// Makes the reference numbers the C++ unit tests compare against.
//
// It does NOT re-type the physics: it cuts the real Orbit Lab functions and data
// straight out of ../../../index.html (the web version, the reference
// implementation), runs them in Node, and writes the results into
// reference_values.h as SI numbers (metres, metres per second, seconds).
//
// Run from the repository root:   node native/tests/reference/make_reference.js
// Only needed again if the web Orbit Lab physics or data change.

'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const html = fs.readFileSync(path.join(__dirname, '../../../index.html'), 'utf8');

// --- small cutting helpers ---------------------------------------------------
// From the first `open` bracket at or after `from`, return the text up to and
// including its matching close bracket (skips over quoted strings).
function matchBlock(text, from, open, close) {
  let i = text.indexOf(open, from), depth = 0, q = null;
  for (; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '\\') i++; else if (c === q) q = null; continue; }
    if (c === '/' && text[i + 1] === '/') { i = text.indexOf('\n', i); continue; }       // skip a // comment (it may hold a ' like "don't")
    if (c === '/' && text[i + 1] === '*') { i = text.indexOf('*/', i) + 1; continue; }
    if (c === "'" || c === '"' || c === '`') { q = c; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return i + 1;
  }
  throw new Error('no matching ' + close);
}
function cutFunction(name) {                       // "function name(...) { ... }"
  const at = html.indexOf('function ' + name + '(');
  if (at < 0) throw new Error('missing function ' + name);
  return html.slice(at, matchBlock(html, at, '{', '}'));
}
function cutStatement(start) {                     // a one-line statement starting with `start` (to the end of its line)
  const at = html.indexOf(start);
  if (at < 0) throw new Error('missing ' + start);
  return html.slice(at, html.indexOf('\n', at));
}
function cutArray(start) {                         // "const X = [ ... ];" (also "... ].map(...);")
  const at = html.indexOf(start);
  if (at < 0) throw new Error('missing ' + start);
  const end = matchBlock(html, at, '[', ']');
  return html.slice(at, html.indexOf('\n', end));
}
function cutObject(start) {                        // "const X = { ... };"
  const at = html.indexOf(start);
  if (at < 0) throw new Error('missing ' + start);
  return html.slice(at, matchBlock(html, at, '{', '}')) + ';';
}
// The Orbit Lab step() is a method inside SIMS['Orbit Lab'] = {...}
const labAt = html.indexOf("SIMS['Orbit Lab'] = {");
const stepAt = html.indexOf('  step(s, p, dt) {', labAt);
const stepSrc = 'function orbitStep' + html.slice(stepAt + '  step'.length, matchBlock(html, stepAt, '{', '}'));
const dtSrc = cutStatement('const DT = ');

const code = [
  cutStatement('const AU = Math.cbrt(100)'),
  cutStatement('const MAX_PLANETS = 12'),
  cutFunction('orbitOf'),
  cutArray('const SOLAR = ['),
  cutFunction('keplerE'),
  cutFunction('keplerState'),
  cutArray('const DWARFS = ['),
  cutObject('const MOONS = {'),
  cutStatement('const hashPhase = '),
  cutFunction('solarBodies'),
  cutArray('const COMETS = ['),
  cutFunction('cometState'),
  cutFunction('baryOf'),
  cutFunction('rng'),
  cutFunction('makeBelts'),
  cutFunction('beltPoint'),
  stepSrc,
  dtSrc,
  'globalThis.R = {AU, YEAR, AU_KM, STAR_R, LOST_R, DT, orbitOf, keplerE, keplerState, solarBodies, baryOf, orbitStep, COMETS, cometState, MOONS, rng, makeBelts, beltPoint};',
].join('\n');
if (process.env.DUMP) fs.writeFileSync(process.env.DUMP, code);
const ctx = {Math, Date, console};
vm.createContext(ctx);
vm.runInContext(code, ctx);
const R = ctx.R;

// --- the exact unit conversions the C++ code uses (see native/src/orbit/units.h) ---
const L = R.AU_KM*1000/R.AU;                       // metres per sim length unit
const T = 365.25*86400/R.YEAR;                     // seconds per sim time unit (1 year = 2π sim units)
const V = L/T;                                     // metres per second per sim speed unit

const EPOCH_MS = Date.UTC(2026, 0, 1, 0, 0, 0);    // 1 Jan 2026 00:00 UTC
const DWARF_NAMES = ['Ceres', 'Pluto', 'Haumea', 'Makemake', 'Eris'];
const fresh = () => { const s = {t: 0, n: 0, count: 0, bodies: [], crashed: 0, escaped: 0, epochMs: EPOCH_MS}; s.bodies = R.solarBodies(s, 8, EPOCH_MS, DWARF_NAMES); return s; };
const p = {GM: 100, tspeed: -0.3};

const out = [];
const num = x => (Number.isFinite(x) ? x.toPrecision(17) : (x > 0 ? 'INFINITY' : '-INFINITY'));
const stateRows = s => s.bodies.map(b => `  {"${b.name}", ${num(b.x*L)}, ${num(b.y*L)}, ${num(b.z*L)}, ${num(b.vx*V)}, ${num(b.vy*V)}, ${num(b.vz*V)}},`).join('\n');

out.push('// Generated by make_reference.js from the web Orbit Lab code in index.html. Do not edit by hand.');
out.push('#pragma once');
out.push('namespace ref {');
out.push(`constexpr long long kEpochMs = ${EPOCH_MS}LL;  // 1 Jan 2026 00:00 UTC`);
out.push('struct BodyState { const char* name; double x, y, z, vx, vy, vz; };  // m and m/s, Sun at the origin');

// 1) starting positions from the NASA/JPL elements (planets, dwarf planets, comets)
let s = fresh();
out.push(`// Positions on the epoch, straight from the orbital elements.\ninline const BodyState kInitial[] = {\n${stateRows(s)}\n};`);

// 2) orbit shape of each body at the epoch
out.push('struct OrbitShape { const char* name; double a_m, e, inclDeg, periodYears; };');
out.push('inline const OrbitShape kOrbits[] = {\n' + s.bodies.map(b => { const o = R.orbitOf(b, 100); return `  {"${b.name}", ${num(o.a*L)}, ${num(o.e)}, ${num(o.incl)}, ${num(o.T)}},`; }).join('\n') + '\n};');

// 3) barycentre at the epoch
{ const bc = R.baryOf(s, p); out.push(`constexpr double kBary[3] = {${num(bc.x*L)}, ${num(bc.y*L)}, ${num(bc.z*L)}};`); }

// 4) leapfrog runs: N fixed steps of DT = 1/240 s (the web's fixed physics step) at a given Time speed
const run = (tspeed, steps) => { const s = fresh(); const pp = {GM: 100, tspeed}; for (let k = 0; k < steps; k++) R.orbitStep(s, pp, R.DT); return s; };
const runs = [['kRunDefault', -0.3, 2400, '10 real seconds at the default Time speed (1 s = about 29 days)'],
              ['kRunFast', 2.5, 240, '1 real second at the fastest Time speed (1 s = about 50 years)'],
              ['kRunRealTime', -6.7009, 240, '1 real second at real time']];
for (const [name, ts, steps, note] of runs) {
  const r = run(ts, steps);
  out.push(`// ${note}: tspeed = ${ts}, ${steps} steps of 1/240 s. Simulated time ${num(r.t*T)} s.`);
  out.push(`constexpr double ${name}Tspeed = ${ts};\nconstexpr int ${name}Steps = ${steps};\nconstexpr double ${name}SimTime = ${num(r.t*T)};`);
  out.push(`inline const BodyState ${name}[] = {\n${stateRows(r)}\n};`);
}

// 5) Kepler's equation at a few hard spots
const ks = [[0, 30], [0.2, 100], [0.9, 1], [0.99917, -0.5], [0.99, 179.9], [0.5, -179]];
out.push('struct KeplerCase { double e, Mdeg, E; };');
out.push('inline const KeplerCase kKepler[] = {\n' + ks.map(([e, M]) => `  {${e}, ${M}, ${num(R.keplerE(e, M))}},`).join('\n') + '\n};');
// 6) belts: the random numbers, and a sample of rocks at the start and 100 years later
{
  const r = R.rng(20260929);
  out.push(`constexpr double kRng[5] = {${[r(), r(), r(), r(), r()].map(num).join(', ')}};`);
  const belts = R.makeBelts(EPOCH_MS, true), o = [0, 0, 0], rows = [];
  const pick = {main: [0, 1, 2, 777, 1799], trojan: [0, 1, 150, 299], kuiper: [0, 1, 450, 899], oort: [0, 1, 799, 800, 2999]};
  const yrs100 = 100*R.YEAR;
  for (const g of belts) for (const k of pick[g.key]) for (const t of [0, yrs100]) {
    if (g.static) { o[0] = g.x[k]; o[1] = g.y[k]; o[2] = g.z[k]; } else R.beltPoint(g, k, t, 100, o);
    rows.push(`  {"${g.key}", ${k}, ${num(t*T)}, ${num(o[0]*L)}, ${num(o[1]*L)}, ${num(o[2]*L)}},`);
  }
  out.push('struct BeltRock { const char* group; int k; double t, x, y, z; };  // t in s after the epoch; position in m');
  out.push('inline const BeltRock kBeltRocks[] = {\n' + rows.join('\n') + '\n};');
  out.push('constexpr int kBeltCounts[4] = {' + belts.map(g => g.n).join(', ') + '};  // main, trojan, kuiper, oort');
}
out.push('}  // namespace ref');

fs.writeFileSync(path.join(__dirname, 'reference_values.h'), out.join('\n') + '\n');
console.log('wrote reference_values.h  (L = ' + L + ' m, T = ' + T + ' s per sim unit)');
