// Makes the reference values the Atom Lab C++ tests compare against (atom_reference.inc).
//
// It does NOT re-type anything: atom_web.js loads the web Atom Lab code out of ../../../index.html
// and this script runs the web's own functions in Node, with Math.random replaced by the same
// seeded generator (mulberry32) the native lab uses, so even the random parts can be compared.
//
// Run from the repository root:   node native/tests/reference/make_atom_reference.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAtomWeb} = require('./atom_web.js');
const {W, ctx, seed} = loadAtomWeb();
const SIM = W.SIM;
const q = s => JSON.stringify(String(s));
const num = x => x === Infinity ? 'INFINITY' : Number.isNaN(x) ? 'NAN' : x.toPrecision(17);
const out = ['// Generated by native/tests/reference/make_atom_reference.js from index.html. Do not edit by hand.'];

// The web engine's setParam (index.html, "function setParam"): clamp to the range, then onParam.
ctx.setParam = (key, val) => {
  const d = SIM.params.find(x => x.key === key);
  if (d.type === 'select') { ctx.params[key] = val; SIM.onParam(ctx.state, ctx.params, key); return; }
  const [lo, hi] = d.limits ? d.limits(ctx.params) : [d.min, d.max];
  ctx.params[key] = Math.max(lo, Math.min(hi, val));
  SIM.onParam(ctx.state, ctx.params, key);
};
const units = u => { ctx.PL_UN = u; };

// ---- 1. element data and the short texts, for every element ----
out.push('struct ElementRef { int Z; const char* name; const char* symbol; int defaultN, nLo, nHi; bool stable; const char* cat; int row, col; const char* state; const char* tempM; const char* tempI; const char* ion; };');
out.push('static const ElementRef kElementRef[] = {');
for (let Z = 1; Z <= 118; Z++) {
  units('metric'); const tm = W.tempLine(Z); units('imperial'); const ti = W.tempLine(Z); units('metric');
  const [r, c] = W.ptPos(Z), st = W.tempState(Z, W.T_ROOM);
  out.push(`  {${Z}, ${q(W.NAME[Z])}, ${q(W.SYMBOL[Z])}, ${W.DEFAULT_N[Z]}, ${W.N_RANGE[Z][0]}, ${W.N_RANGE[Z][1]}, ${W.hasStable(Z)}, ${q(W.CAT[Z].nm)}, ${r}, ${c}, ${q(st || '')}, ${q(tm)}, ${q(ti)}, ${q(W.ionLabel(Z))}},`);
}
out.push('};');

// ---- 2. every known nuclide (and a step beyond each end): the one-line description ----
out.push('struct NuclideRef { int Z, N; const char* line; const char* info; };');
out.push('static const NuclideRef kNuclideRef[] = {');
for (let Z = 1; Z <= 118; Z++) {
  const ns = Object.keys(W.NUC[Z]).map(Number), lo = Math.min(...ns) - 1, hi = Math.max(...ns) + 1;
  for (let N = Math.max(0, lo); N <= hi; N++) out.push(`  {${Z}, ${N}, ${q(W.isoLine(Z, N))}, ${q(W.isoInfo(Z, N))}},`);
}
out.push('};');

// ---- 3. every decay mode in the data ----
const modes = new Set();
for (let Z = 1; Z <= 118; Z++) for (const N of Object.keys(W.NUC[Z]).map(Number).concat([0, 1, 2, 300])) { const d = W.decInfo(Z, N); if (d) d.br.forEach(([m]) => modes.add(m)); }
out.push('struct ModeRef { const char* m; bool moves; int dZ, dN; const char* word; const char* shortWord; const char* shots; };');
out.push('static const ModeRef kModeRef[] = {');
for (const m of [...modes].sort()) {
  const mv = W.decMove(m), shots = W.decShots(m).map(s => s.join('/')).join(' ');
  out.push(`  {${q(m)}, ${!!mv}, ${mv ? mv[0] : 0}, ${mv ? mv[1] : 0}, ${q(W.decWord(m))}, ${q(W.DEC_SHORT(m))}, ${q(shots)}},`);
}
out.push('};');

// ---- 4. numbers: binding energy, shape, sizes ----
out.push('struct NucNumRef { int Z, N; double B; bool real; double beta; bool measured; double R; };');
out.push('static const NucNumRef kNucNumRef[] = {');
for (let Z = 1; Z <= 118; Z++) for (const N of [...new Set([W.N_RANGE[Z][0], W.DEFAULT_N[Z], W.N_RANGE[Z][1]])]) {
  const b = W.massBinding(Z, N);
  out.push(`  {${Z}, ${N}, ${num(b.B)}, ${b.real}, ${num(W.nucBeta(Z, N))}, ${W.nucMeasured(Z, N)}, ${num(W.nuclearR(Z + N))}},`);
}
out.push('};');

// ---- 5. number formats ----
const fmts = [];
const vals = [3e-23, 1e-22, 4.2e-10, 2.99e-7, 1e-6, 1.5e-6, 4.5e-4, 0.0123, 0.3, 0.5, 0.999, 1, 2.5, 9.995, 55.6, 59.9, 3599, 7200, 86399.9, 1e5,
              8.64e6, 1.7e7, 3.155e7, 1.8e9, 2.4e12, 3.16e13, 1.4e17, 4.4e17, 3.2e19, 7e25, 1e30];
for (const v of vals) {
  fmts.push(['fmtHalf', v, W.fmtHalf(v)], ['fmtHalf2', v, W.fmtHalf(v, 2)], ['fmtLife', v, W.fmtLife(v)], ['sci', v, W.sci(v)], ['metres', v, W.metres(v)]);
}
for (const v of [0.0005, 0.004, 0.0098, 0.03, 0.0999, 0.1, 0.52, 2.12, 8.47, 99.9, 121.57, 656.47, 1875.6, 4051]) fmts.push(['fmtLam', v, W.fmtLam(v)], ['fmtLen', v, W.fmtLen(v)], ['fmtT', v, W.fmtT(v)]);
for (const v of [0.66, 1.89, 10.2, 13.6, 54.4, 999.999, 1000, 9183, 99999, 1e5, 1.23e5]) fmts.push(['fmtEV', v, W.fmtEV(v)]);
for (const v of [0, 1e-19, 3e-15, 5.3e-11, 0.007, 0.05, 0.123, 1, 9.99, 12.345, 999.5, 9999.4, 12345, 1.2e6, 3.844e8]) {
  fmts.push(['lrnSci', v, W.lrnSci(v)], ['lrnSci3', v, W.lrnSci3(v)], ['lrnSci3_2', v, W.lrnSci3(v, 2)]);
  units('metric'); fmts.push(['lrnLenM', v, W.lrnLen(v)]); units('imperial'); fmts.push(['lrnLenI', v, W.lrnLen(v)]); units('metric');
}
for (const v of [0, 7, 12, -5, 238, 1000]) fmts.push(['supDigits', v, W.supDigits(v)]);
for (const [Z, N] of [[1, 0], [1, 1], [1, 2], [2, 2], [6, 8], [92, 146], [118, 176]]) fmts.push(['nuclideLabel', Z * 1000 + N, W.nuclideLabel(Z, N)]);
for (const k of [1.5, 4.22, 99.94, 100, 273.15, 293.15, 1234.4, 5869]) fmts.push(['fK', k, W.fK(k)], ['fC', k, W.fC(k)], ['fF', k, W.fF(k)]);
out.push('struct FmtRef { const char* f; double x; const char* text; };');
out.push('static const FmtRef kFmtRef[] = {');
for (const [f, x, t] of fmts) if (t !== '') out.push(`  {${q(f)}, ${num(x)}, ${q(t)}},`);
out.push('};');

// ---- 6. orbitals: ψ at fixed points, Laguerre coefficients, the dipole rule ----
const full = Object.keys(W.ORB).filter(k => W.ORB[k].ang);
out.push('static const char* const kOrbKeys[] = {' + full.map(q).join(', ') + '};');
out.push('static const char* const kOrbTxt[] = {' + full.map(k => q(W.ORB[k].txt)).join(', ') + '};');
out.push('struct PsiRef { const char* key; int Z; double x, y, z, v; };');
out.push('static const PsiRef kPsiRef[] = {');
const pts = [[0.3, 0.2, -0.5], [1.1, -0.7, 0.4], [-2.5, 1.5, 3.2], [6, -4, 8], [0.01, 0.02, 0.03]];
for (const k of full) for (const Z of [1, 3, 26]) for (const [x, y, z] of pts) out.push(`  {${q(k)}, ${Z}, ${x}, ${y}, ${z}, ${num(W.psi(k, Z, x, y, z))}},`);
out.push('};');
out.push('struct LagRef { int k; double a; double c[4]; };');
out.push('static const LagRef kLagRef[] = {');
for (let k = 0; k <= 3; k++) for (let a = 1; a <= 7; a += 2) { const c = W.lagCoef(k, a); out.push(`  {${k}, ${a}, {${[0, 1, 2, 3].map(i => num(c[i] || 0)).join(', ')}}},`); }
out.push('};');
out.push('static const char* const kDipoleRef = ' + q(full.map(a => full.map(b => W.dipoleOK(a, b) ? '1' : '0').join('')).join('')) + ';');

// ---- 7. light ----
out.push('struct SpecRef { int Z, N; double ryd; double lam[105]; };');
out.push('static const SpecRef kSpecRef[] = {');
for (const [Z, N] of [[1, 0], [1, 1], [2, 2], [26, 30], [118, 176]]) out.push(`  {${Z}, ${N}, ${num(W.rydM(Z, N))}, {${W.specLines(Z, N).map(L => num(L.lam)).join(', ')}}},`);
out.push('};');
out.push('struct ColRef { double lam; const char* css; };');
out.push('static const ColRef kColRef[] = {' + [200, 379, 380, 400, 419, 430, 450, 489, 500, 509, 550, 579, 600, 644, 656.47, 700, 701, 760, 780, 781, 1875].map(l => `{${l}, ${q(W.lamColor(l))}}`).join(', ') + '};');

// ---- 8. seeded nuclei: every nucleon's place (fm) ----
out.push('struct NucleonRef { double x, y, z; bool isP; double ph; };');
out.push('struct NucleusRef { uint32_t seed; int Z, N; std::vector<NucleonRef> n; };');
out.push('static const NucleusRef kNucleusRef[] = {');
for (const [sd, Z, N] of [[11, 1, 0], [12, 1, 1], [13, 2, 1], [14, 2, 2], [15, 6, 6], [16, 8, 8], [17, 26, 30], [18, 92, 146], [19, 64, 94], [20, 14, 14]]) {
  seed(sd); const nuc = W.buildNucleus(Z, N);
  out.push(`  {${sd}, ${Z}, ${N}, {${nuc.map(c => `{${num(c.x)}, ${num(c.y)}, ${num(c.z)}, ${!!c.isP}, ${num(c.ph)}}`).join(', ')}}},`);
}
out.push('};');

// ---- 9. seeded runs of the whole lab: a script of actions, with the readout and the state at each check ----
// ops: seed s · set key value · tick dt · steps count (fixed 1/240 s steps) · emit · absorb · auto · pause · resume · check
const DT = 1/240;
const scripts = [
  [['seed', 1], ['steps', 480], ['check'], ['emit'], ['check'], ['absorb'], ['steps', 400], ['check'], ['set', 'n', 3], ['steps', 240], ['check'],
   ['set', 'speed', 30], ['steps', 600], ['check'], ['emit'], ['steps', 10], ['check'], ['set', 'ostyle', 'Bohr 1913'], ['check'], ['set', 'Z', 26], ['steps', 240], ['check']],
  [['seed', 2], ['set', 'view', 'Cloud'], ['steps', 480], ['check'], ['absorb'], ['check'], ['steps', 400], ['check'], ['set', 'orb', '3d'], ['set', 'dAx', 'xy'], ['steps', 240], ['check'],
   ['emit'], ['steps', 300], ['check'], ['set', 'zoom', 2.5], ['check'], ['set', 'view', 'Slice'], ['set', 'cut', 0.3], ['steps', 120], ['check'], ['emit'], ['check']],
  [['seed', 3], ['set', 'view', 'Cloud 3D'], ['set', 'Z', 3], ['set', 'orb', '4f'], ['set', 'fAx', 'xyz'], ['steps', 240], ['check'], ['auto'], ['steps', 2400], ['check'], ['steps', 2400], ['check'],
   ['set', 'scale', 'Fixed'], ['set', 'zoom', 4.2], ['check']],
  [['seed', 4], ['set', 'Z', 83], ['set', 'N', 129], ['tick', 0.016], ['check'], ['tick', 3600], ['check'], ['tick', 3600], ['tick', 3600], ['tick', 3600], ['check'],
   ['tick', 1e5], ['tick', 1e5], ['check'], ['set', 'Z', 84], ['set', 'N', 128], ['tick', 0.016], ['tick', 0.016], ['check'], ['pause'], ['set', 'Z', 92], ['set', 'N', 141], ['tick', 0.016], ['check'],
   ['resume'], ['tick', 1e9], ['check'], ['set', 'Z', 98], ['set', 'N', 154], ['tick', 0.016], ['tick', 1e12], ['check']],
  [['seed', 5], ['set', 'Z', 118], ['steps', 120], ['check'], ['set', 'zoom', 4.5], ['set', 'view', 'Cloud'], ['steps', 120], ['check'], ['set', 'Z', 2], ['set', 'N', 1], ['tick', 0.5], ['steps', 30], ['check'],
   ['set', 'Z', 4], ['set', 'N', 4], ['tick', 0.016], ['tick', 0.016], ['check']],
];
out.push('struct Op { const char* op; const char* key; double v; const char* sv; };');
out.push('struct Check { std::vector<std::string> info; std::string hint, chain, log; double x, y, vx, vy; long k; double pts[6]; };');
out.push('struct RunRef { std::vector<Op> ops; std::vector<Check> checks; };');
out.push('static const RunRef kRunRef[] = {');
for (const ops of scripts) {
  const checks = [];
  for (const [op, a, b] of ops) {
    if (op === 'seed') { seed(a); ctx.paused = false; ctx.params = {}; SIM.params.forEach(d => { ctx.params[d.key] = d.value; }); ctx.state = SIM.init(ctx.params); W.DEC_CHAIN = []; }
    else if (op === 'set') ctx.setParam(a, b);
    else if (op === 'tick') SIM.tick(ctx.state, ctx.params, a);
    else if (op === 'steps') for (let i = 0; i < a; i++) SIM.step(ctx.state, ctx.params, DT);
    else if (op === 'emit') W.manualJump(ctx.state, ctx.params, -1);
    else if (op === 'absorb') W.manualJump(ctx.state, ctx.params, 1);
    else if (op === 'auto') { ctx.state.auto = !ctx.state.auto; ctx.state.wait = 0.3; }
    else if (op === 'pause') ctx.paused = true;
    else if (op === 'resume') ctx.paused = false;
    else if (op === 'check') {
      const s = ctx.state, info = [].concat(SIM.info(s, ctx.params));
      const chain = W.DEC_CHAIN.map(c => c.nuc || `${c.how}|${+c.lived.toPrecision(6)}|${c.to}`).join(' > '), log = (s.decLog || []).map(L => L.txt).join('\n');
      const a0 = W.A0*1e-10, au_v = a0/(W.AU_T*1e-18);
      checks.push(`{{${info.map(q).join(', ')}}, ${q(SIM.hint(ctx.params))}, ${q(chain)}, ${q(log)}, ${num(s.x*a0)}, ${num(s.y*a0)}, ${num(s.vx*au_v)}, ${num(s.vy*au_v)}, ${s.k}, {${[0, 1, 2, 3, 4, 5].map(i => num(s.pts[i]*a0)).join(', ')}}}`);
    }
  }
  const opsC = ops.map(([op, a, b]) => `{${q(op)}, ${typeof a === 'string' ? q(a) : '""'}, ${typeof a === 'number' ? num(a) : typeof b === 'number' ? num(b) : 0}, ${typeof b === 'string' ? q(b) : '""'}}`);
  out.push(`  {{${opsC.join(', ')}},\n   {${checks.join(',\n    ')}}},`);
}
out.push('};');

fs.writeFileSync(path.join(__dirname, 'atom_reference.inc'), out.join('\n') + '\n');
console.log('wrote atom_reference.inc', (out.join('\n').length/1024).toFixed(0) + ' KB');
