// Records the Atom Lab Learn guides' text, made by the web's own functions (lrnLook, lrnScale,
// lrnMass) in Node with a small fake page (fake_dom.js), for a list of atoms and views, in metric
// and imperial. tests/test_atom.cpp checks the native text against it word for word.
// Run from the repository root:   node native/tests/reference/make_atom_learn_reference.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAtomWeb} = require('./atom_web.js');
const {makeEl, serialize, fold} = require('./fake_dom.js');
const {W, ctx} = loadAtomWeb();
const q = s => JSON.stringify(String(s));
const out = ['// Generated by native/tests/reference/make_atom_learn_reference.js from index.html. Do not edit by hand.'];
const cases = [
  {Z: 1, N: 0}, {Z: 1, N: 1}, {Z: 2, N: 2, view: 'Cloud', orb: '2p'}, {Z: 6, N: 8, view: 'Slice', orb: '3d'}, {Z: 26, N: 30, view: 'Cloud 3D', orb: '4f'},
  {Z: 26, N: 30, ostyle: 'Bohr 1913'}, {Z: 82, N: 126}, {Z: 92, N: 146, view: 'Cloud'}, {Z: 118, N: 176}, {Z: 4, N: 0}, {Z: 3, N: 1}, {Z: 50, N: 70, view: 'Slice'},
  {Z: 110, N: 150}, {Z: 20, N: 20, ostyle: 'Bohr 1913'},
];
const find = (e, cls) => { if (typeof e !== 'object') return null; if ((' ' + e.className + ' ').includes(' ' + cls + ' ')) return e; for (const c of e.children) { const f = find(c, cls); if (f) return f; } return null; };
out.push('struct LearnRef { int Z, N; const char* view; const char* ostyle; const char* orb; bool imperial; const char* live;');
out.push('  std::vector<std::string> look;    // key|title|html for each section');
out.push('  std::vector<std::string> scale;   // ten, then the five objects');
out.push('  std::vector<std::string> mass;    // parts, miss, count, proton, ladder');
out.push('};');
out.push('static const LearnRef kLearnRef[] = {');
for (const [ci, c] of cases.entries()) for (const units of ci < 3 ? ['metric', 'imperial'] : ['metric']) {
  ctx.PL_UN = units;
  const p = {}; W.SIM.params.forEach(d => p[d.key] = d.value); Object.assign(p, c); ctx.params = p; ctx.state = W.SIM.init(p);
  const live = [].concat(W.SIM.info(ctx.state, p)).join('<br>');
  // look
  const b1 = makeEl('div'); W.lrnLook(b1, p, null);
  const lo = find(b1, 'lrnOut'), look = lo.children.filter(e => e.className === 'lrnSecP').map(s => `${s.dataset.k}|${s.dataset.t}|${fold(s.children[1].innerHTML)}`);
  // scale: the tabs, and the object chips
  const b2 = makeEl('div'); W.lrnScale(b2, p, null);
  const tabs2 = find(b2, 'lrnTabs'), out2 = find(b2, 'lrnOut'), scale = [];
  tabs2.children[1].onclick(); scale.push(fold(out2.children.map(serialize).join('')));
  for (let i = 0; i < 5; i++) { tabs2.children[0].onclick(); find(out2, 'lrnChips').children[i].onclick(); scale.push(fold(out2.children.map(serialize).join(''))); }
  // mass: the five tabs
  const b3 = makeEl('div'); W.lrnMass(b3, p, null);
  const tabs3 = find(b3, 'lrnTabs'), out3 = find(b3, 'lrnOut'), mass = [];
  for (let i = 0; i < 5; i++) { tabs3.children[i].onclick(); mass.push(fold(out3.children.map(serialize).join(''))); }
  out.push(`  {${p.Z}, ${p.N}, ${q(p.view)}, ${q(p.ostyle)}, ${q(p.orb)}, ${units === 'imperial'}, ${q(live)},\n   {${look.map(q).join(',\n    ')}},\n   {${scale.map(q).join(',\n    ')}},\n   {${mass.map(q).join(',\n    ')}}},`);
}
out.push('};');

// ---- the panel's texts: run the web's own buildUI with the fake page, then read what it wrote ----
const panel = units => {
  ctx.PL_UN = units;
  const p = {}; W.SIM.params.forEach(d => p[d.key] = d.value); ctx.params = p; ctx.state = W.SIM.init(p);
  ctx.ui = {Z: {inp: makeEl('input')}, N: {inp: makeEl('input')}};
  ctx.css = () => ({fg: '#eee', muted: '#999', accent: '#6c9cff', card: '#1e1e21', line: '#333'});
  ctx.LEARN = {'Atom Lab': []};
  const cards = {}, h2 = {};
  const getCard = g => { if (!cards[g]) { const c = makeEl('div'), h = makeEl('h2'); h.after = (...a) => { h.list = a; }; c.querySelector = () => h; cards[g] = c; h2[g] = h; } return cards[g]; };
  const upd = W.SIM.buildUI(getCard, ctx.setParam, p);
  const [grid, bigB, hl, info, facts] = h2.Nucleus.list;
  const tin = cards.Temperature.children[0].children[0], tst = cards.Temperature.children[1], tsp = cards.Temperature.children[2];
  const snote = cards['Light spectrum'].children[1], hlist = cards['Decay history'].children[0];
  return {p, upd, hl, info, facts, tin, tst, tsp, snote, hlist};
};
out.push('struct PanelRef { int Z, N; bool imperial; double tempK; std::vector<std::string> chain; const char* iso; const char* card; const char* facts; const char* spectrum; const char* tState; const char* tSpeed; std::vector<std::string> hist; };');
out.push('static const PanelRef kPanelRef[] = {');
const pcases = [[1, 0, 293.15], [1, 1, 0], [2, 2, 3], [6, 6, 4000], [15, 16, 300], [16, 16, 388.5], [26, 30, 1811.4], [31, 39, 310], [33, 42, 900], [35, 44, 270],
  [43, 55, 2500], [55, 78, 301.6], [80, 122, 250], [85, 125, 600], [92, 146, 5999], [98, 153, 1500], [104, 163, 2000], [118, 176, 20], [83, 126, 0.04], [94, 145, 12.5]];
const chains = [[], [{nuc: 'Bi-212'}], [{nuc: 'Fe-56'}], [{nuc: 'Bi-212'}, {how: 'β⁻', lived: 3600.5, to: 'Po-212'}, {how: 'α', lived: 3e-7, to: 'Pb-208'}],
  [{nuc: 'U-238'}, {how: 'split in two (fission)', lived: 1.2e17, to: null}], [{nuc: 'Og-294'}, {how: 'α', lived: 0.0007, to: null}]];
for (const units of ['metric', 'imperial']) {
  const P = panel(units);
  pcases.forEach(([Z, N, K], i) => {
    if (units === 'imperial' && i % 3) return;
    const chain = chains[i % chains.length];
    W.DEC_CHAIN = chain;
    P.p.Z = Z; P.p.N = N;
    P.tin.value = 1000*Math.sqrt(K/W.T_MAX); P.tin.oninput();
    P.upd(P.p); P.upd(P.p);
    const hist = P.hlist.children.map(c => c.className + '|' + c.textContent);
    const ch = chain.map(c => c.nuc ? c.nuc : `${c.how}|${c.lived}|${c.to == null ? '' : c.to}`);
    out.push(`  {${Z}, ${N}, ${units === 'imperial'}, ${W.T_MAX*(P.tin.value/1000)**2}, {${ch.map(q).join(', ')}}, ${q(P.hl.textContent)}, ${q(P.info.innerHTML)}, ${q(P.facts.innerHTML)}, ${q(P.snote.innerHTML)}, ${q(P.tst.innerHTML)}, ${q(P.tsp.innerHTML)}, {${hist.map(q).join(', ')}}},`);
  });
}
out.push('};');
// ---- every element: 64-bit FNV-1a hashes of the card, facts and "where you meet it" texts (both units) ----
const fnv = str => { let h = 0xcbf29ce484222325n; for (const b of Buffer.from(str, 'utf8')) { h ^= BigInt(b); h = (h * 0x100000001b3n) & 0xffffffffffffffffn; } return '0x' + h.toString(16) + 'ull'; };
out.push('struct ElementTextRef { int Z; uint64_t card, factsM, factsI, everyM, everyI; };');
out.push('static const ElementTextRef kElementTextRef[] = {');
for (let Z = 1; Z <= 118; Z++) {
  ctx.PL_UN = 'metric'; const card = W.elemCardHTML(Z), fM = W.factsHTML(Z), eM = W.uText(W.everyday(Z));
  ctx.PL_UN = 'imperial'; const fI = W.factsHTML(Z), eI = W.uText(W.everyday(Z));
  out.push(`  {${Z}, ${fnv(card)}, ${fnv(fM)}, ${fnv(fI)}, ${fnv(eM)}, ${fnv(eI)}},`);
}
ctx.PL_UN = 'metric';
out.push('};');
fs.writeFileSync(path.join(__dirname, 'atom_learn_reference.inc'), out.join('\n') + '\n');
console.log('wrote atom_learn_reference.inc', (out.join('\n').length/1024).toFixed(0) + ' KB');
