// Runs the web's Settings → Progress and Developer code (index.html) for every mix of unlocked secret
// themes (0–2) and achievements (0–5) and writes what it shows to app_reference.inc, for test_app.cpp:
// the "Reset your progress?" pop-up, the "Progress reset" pop-up after "Yes", and the line after
// "Unlock everything". Run from the repository root:   node native/tests/reference/make_app_reference.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAppWeb} = require('./app_web.js');
const q = s => JSON.stringify(String(s));
const walk = (e, f) => { if (!e || typeof e !== 'object') return; f(e); (e.children || []).forEach(c => walk(c, f)); };
const all = (root, cls) => { const out = []; walk(root, e => { if ((' ' + e.className + ' ').includes(' ' + cls + ' ')) out.push(e); }); return out; };
const ids = loadAppWeb().A.PLAch.list.map(x => x.id);
// the pop-up's buttons: querySelector('#rstYes') gives the same button each time, so the web's onclick can be pressed
const {makeEl} = require('./fake_dom.js');
const load = storage => {
  const w = loadAppWeb({storage});
  w.ctx.document.createElement = tag => { const e = makeEl(tag), qs = {}; e.querySelector = sel => qs[sel] || (qs[sel] = makeEl('button')); e.btn = qs; return e; };
  return w;
};
const strip = h => h.replace(/^<div id="gift" role="dialog" aria-modal="true">/, '').replace(/<\/div>$/, '');
const o = ['// Generated by native/tests/reference/make_app_reference.js from index.html. Do not edit by hand.',
  'struct ResetRef { int themes, achievements; const char* ask; const char* done; const char* unlock; };',
  'static const ResetRef kResetRef[] = {'];
for (let t = 0; t <= 2; t++) for (let a = 0; a <= ids.length; a++) {
  const storage = {plUnlock: ['synthwave', 'monochrome'].slice(0, t).join(','), plAch: JSON.stringify(Object.fromEntries(ids.slice(0, a).map(x => [x, 0])))};
  // the reset pop-up, then "Yes"
  let w = load(storage);
  w.els('settingsBtn').onclick(); all(w.ctx.lastBox, 'setRow')[0].onclick();
  let bg = w.body.children.find(e => e.id === 'giftBg');
  const ask = strip(bg.innerHTML);
  let done = '';
  const yes = bg.btn['#rstYes'];
  if (yes && yes.onclick) { yes.onclick(); done = strip(bg.innerHTML); }
  // "Unlock everything" from the same start
  w = load(storage);
  w.els('settingsBtn').onclick(); all(w.ctx.lastBox, 'setRow')[1].onclick();
  const unlock = all(w.ctx.lastBox, 'setDone').map(e => e.innerHTML).pop();
  o.push(`  {${t}, ${a}, ${q(ask)},\n   ${q(done)},\n   ${q(unlock)}},`);
}
o.push('};');

// the header, About, the language menu and the history, from one more run of the web page
{
  const w = loadAppWeb();
  const hdr = /<header>.*<\/header>/.exec(w.html)[0];
  o.push('struct HeaderRef { const char* id; const char* label; const char* tip; };');
  o.push('static const HeaderRef kHeaderRef[] = {' + [...hdr.matchAll(/<button id="(\w+)" class="ver" title="([^"]*)"[^>]*>([^<]*)<\/button>/g)].map(m => `{${q(m[1])}, ${q(m[3])}, ${q(m[2])}}`).join(', ') + '};');
  w.ctx.SIMS = {'Orbit Lab': {update: '7.7.2'}, 'Atom Lab': {update: '7.7.3'}};
  w.els('aboutBtn').onclick();
  const {serialize} = require('./fake_dom.js');
  o.push(`static const char* const kAboutRefTitle = ${q(w.ctx.lastTitle)};`);
  o.push(`static const char* const kAboutRef = ${q(w.ctx.lastBox.children.map(serialize).join(''))};`);
  w.els('langBtn').onclick();
  o.push(`static const char* const kLangRef[] = {${w.body.children.find(e => e.id === 'langMenu').children.map(b => q(b.innerHTML)).join(', ')}};`);
  o.push(`static const char* const kLangLabelRef = ${q(w.els('langBtn').textContent)};`);
  w.els('appLog').onclick();
  o.push(`static const char* const kHistoryRefTitle = ${q(w.ctx.lastTitle)};`);
  // each timeline row's text part: "<div class=\"lrnY\">…</div><div class=\"lrnTt\">…</div><div class=\"lrnD\">…</div>" and its button
  const rows = w.ctx.lastBox.children.find(e => e.className === 'lrnTl').children;
  o.push(`static const char* const kHistoryRef[] = {${rows.map(r => q(r.children[1].innerHTML + (r.children[1].children.length ? '|' + r.children[1].children.map(c => c.innerHTML).join('|') : ''))).join(',\n  ')}};`);
  o.push(`static const char* const kHistoryRefFirst = ${q(w.ctx.lastBox.children[0].innerHTML)};`);
  o.push(`static const char* const kHistoryRefLast = ${q(w.ctx.lastBox.children[w.ctx.lastBox.children.length - 1].innerHTML)};`);
}
// 💡 the facts, the 🎁 pop-up (tap the line until the 🎁 comes, then tap it) and the Monochrome pop-up, first find and again
{
  const w = loadAppWeb();
  o.push(`static const char* const kDykRef[] = {${w.A.DYK.map(q).join(',\n  ')}};`);
  // each tap shows the next fact (the fake page skips the 0.25 s fade); the tap that lands on the 🎁 opens its pop-up
  const giftOf = w => { const bg = () => w.body.children.find(e => e.id === 'giftBg'); for (let i = 0; i < 60 && !bg(); i++) w.els('dyk').onclick(); return strip(bg().innerHTML.replace(/ aria-labelledby="giftT"/, '')); };
  const g1 = giftOf(w);
  const w2 = loadAppWeb({storage: {plUnlock: 'synthwave'}});
  const g2 = giftOf(w2);
  o.push(`static const char* const kGiftSynthRef[2] = {${q(g1)}, ${q(g2)}};`);
  const m = st => { const v = loadAppWeb({storage: st}); v.A.PLTheme.secretMono(); return strip(v.body.children.find(e => e.id === 'giftBg').innerHTML.replace(/ aria-labelledby="monoT"/, '')); };
  o.push(`static const char* const kGiftMonoRef[2] = {${q(m({}))}, ${q(m({plUnlock: 'monochrome'}))}};`);
}
// 🏆 the Achievements tab with two earned (one with a date at noon UTC, one "earlier"), and 📚 the Learn tab
{
  const ach = {decay: Date.UTC(2026, 8, 5, 12), galactic: 0};
  const w = loadAppWeb({storage: {plAch: JSON.stringify(ach)}});
  w.A.paintAch();
  const P = w.ctx.achPane.children;
  o.push(`static const char* const kAchHeadRef = ${q(P[0].innerHTML)};   // the web counts 5 achievements`);
  o.push(`static const char* const kAchCardsRef[] = {${P[1].children.map(c => q(c.className + '|' + c.innerHTML)).join(',\n  ')}};`);
  o.push('struct DateRef { long long ms; const char* text; };');
  o.push(`static const DateRef kDateRef[] = {${[...Array(12).keys()].map(mo => { const t = Date.UTC(2026, mo, 1 + 2 * mo, 12); return `{${t}LL, ${q(new Date(t).toLocaleDateString('en-GB', {day: 'numeric', month: 'short', year: 'numeric'}))}}`; }).join(', ')}};`);
  w.A.paintLearn();
  const L = w.ctx.achPane.children;
  o.push(`static const char* const kLearnHeadRef = ${q(L[0].innerHTML)};`);
  o.push(`static const char* const kLearnRef[] = {${L.filter(e => e.className === 'learnSec').flatMap(sec => [q('h3|' + sec.children[0].innerHTML), ...sec.children[1].children.map(c => q(c.innerHTML))]).join(',\n  ')}};`);
}
fs.writeFileSync(path.join(__dirname, 'app_reference.inc'), o.join('\n') + '\n');
console.log('wrote app_reference.inc');
