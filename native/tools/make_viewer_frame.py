#!/usr/bin/env python3
"""0.21 stage 1: writes src/molecule/viewer_frame.inc from data/molecules/xyz/*.xyz.

The 15 viewer molecules are drawn in EXACTLY the frame their electron density was computed in (the .xyz files, made on Linux by the molecule_xyz tool
from the CCCBDB values). The app no longer re-diagonalises their inertia tensor at start-up: for a molecule with two equal moments (benzene, the
symmetric tops) the in-plane axes are fixed only by rounding, and MSVC turned benzene in its plane differently from GCC (the first 0.21 Windows run).
Usage (from native/): python3 tools/make_viewer_frame.py data/molecules/xyz src/molecule/viewer_frame.inc
"""
import os, sys
src, out = sys.argv[1], sys.argv[2]
lines = ["// Generated by tools/make_viewer_frame.py from data/molecules/xyz (angstrom, the frame the density data was computed in). Do not edit.",
         "struct FrameAtom { const char* el; double x, y, z; };",
         "struct Frame { const char* id; int n; FrameAtom atoms[12]; };",
         "const Frame kViewerFrame[] = {"]
for f in sorted(os.listdir(src)):
    if not f.endswith(".xyz"): continue
    rows = open(os.path.join(src, f)).read().splitlines()
    n = int(rows[0])
    at = ", ".join("{\"%s\", %s, %s, %s}" % tuple(r.split()[:4]) for r in rows[2:2 + n])
    lines.append("    {\"%s\", %d, {%s}}," % (f[:-4], n, at))
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
