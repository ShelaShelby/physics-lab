#!/usr/bin/env python3
"""Fetch the measured nuclear charge radii the Atom Lab sizes its nuclei with, check them, and write the file the app is built from.

Python 3, standard library only. Run from anywhere:
    python3 native/tools/make_radii_data.py fetch    (needs network: www-nds.iaea.org; writes native/data/radii/charge_radii.csv)
    python3 native/tools/make_radii_data.py build    (offline: reads that CSV, writes native/src/atom/radii_data.inc)

fetch : one plain GET of  https://www-nds.iaea.org/radii/charge_radii.csv  (IAEA Nuclear Data Section). The file is saved exactly as received. The IAEA's web PAGES
        (www-nds.iaea.org/radii/ and the interactive services) sit behind a bot challenge that no script can pass; this one static file is not behind it (0.10.9 stage 1).
build : checks the file and writes src/atom/radii_data.inc (a C++ table of Z, N, rms charge radius, its uncertainty and the preliminary value, all in fm).
        Nothing is invented: a cell is exactly what the file says; a value the file leaves empty is NaN in the table.

What the columns are (names as in the file's header): z, symbol, n (neutrons), a (mass number), radius_val and radius_unc (the rms charge radius and its uncertainty, fm),
radius_preliminary_val and radius_preliminary_unc (a preliminary value, fm). The file has no unit column and no text; the unit fm is the compilation's (see data/radii/README.txt).
The row z = 0 (the neutron) has a NEGATIVE value (-0.1149): a radius cannot be negative, so it can only be a mean-square charge radius in fm^2 (the task text says so too; the file does not).
It is left out of the table on purpose.
"""
import csv
import hashlib
import math
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                                     # native/
DATA = os.path.join(ROOT, "data", "radii")
CSV_PATH = os.path.join(DATA, "charge_radii.csv")
OUT_INC = os.path.join(ROOT, "src", "atom", "radii_data.inc")
URL = "https://www-nds.iaea.org/radii/charge_radii.csv"
HEADER = ["z", "symbol", "n", "a", "radius_val", "radius_unc", "radius_preliminary_val", "radius_preliminary_unc"]


def die(msg):
    sys.exit("make_radii_data.py: " + msg)


def fetch():
    req = urllib.request.Request(URL, headers={"User-Agent": "PhysicsLab-native-data-tool"})
    with urllib.request.urlopen(req, timeout=120) as r:
        body = r.read()
        print("HTTP", r.status, r.headers.get("Content-Type"), "Last-Modified:", r.headers.get("Last-Modified"))
    os.makedirs(DATA, exist_ok=True)
    with open(CSV_PATH, "wb") as f:
        f.write(body)
    print("wrote", CSV_PATH, len(body), "bytes, %d lines, sha256 %s" % (body.count(b"\n"), hashlib.sha256(body).hexdigest()))


def num(s):
    return None if s == "" else float(s)


def read_rows():
    with open(CSV_PATH, newline="", encoding="ascii") as f:
        rd = csv.reader(f)
        head = next(rd)
        if head != HEADER:
            die("unexpected header: %r" % head)
        rows = []
        for ln, c in enumerate(rd, start=2):
            if len(c) != 8:
                die("line %d: %d cells" % (ln, len(c)))
            z, n, a = int(c[0]), int(c[2]), int(c[3])
            if a != z + n:
                die("line %d: a != z + n" % ln)
            rows.append((z, c[1], n, a, num(c[4]), num(c[5]), num(c[6]), num(c[7])))
    return rows


def build():
    rows = read_rows()
    out, seen = [], set()
    for z, sym, n, a, v, u, pv, pu in rows:
        if z == 0:
            if not (v is not None and v < 0):
                die("the neutron row changed: check what it is before using the file")
            continue                                             # the neutron: a negative number, a mean-square radius in fm^2, not a radius
        if (z, n) in seen:
            die("duplicate %s-%d" % (sym, a))
        seen.add((z, n))
        if v is None and pv is None:
            die("%s-%d has no value at all" % (sym, a))
        if (v is None) != (u is None) or (pv is None) != (pu is None):
            die("%s-%d: a value without its uncertainty" % (sym, a))
        for x in (v, u, pv, pu):
            if x is not None and not (x >= 0 and math.isfinite(x)):
                die("%s-%d: bad number" % (sym, a))
        out.append((z, n, v, u, pv, pu))
    out.sort()

    def c(x):
        return "NAN" if x is None else repr(x)

    lines = ["// GENERATED by native/tools/make_radii_data.py from data/radii/charge_radii.csv (IAEA Nuclear Data Section, see data/radii/README.txt). Do not edit.",
             "// One row per isotope in the file, sorted by Z then N: Z, N, rms charge radius (fm), its uncertainty (fm), preliminary rms charge radius (fm), its uncertainty (fm); NAN where the file leaves a cell empty.",
             "// The neutron row (z = 0, a negative number: a mean-square radius in fm^2) is not in this table. %d rows." % len(out),
             "static const RadiusRow kRadiusRows[] = {"]
    for z, n, v, u, pv, pu in out:
        lines.append("    {%d, %d, %s, %s, %s, %s}," % (z, n, c(v), c(u), c(pv), c(pu)))
    lines.append("};")
    with open(OUT_INC, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    withv = sum(1 for r in out if r[2] is not None)
    print("wrote", OUT_INC, "%d rows: %d with a value, %d preliminary only, %d with both" % (len(out), withv, len(out) - withv, sum(1 for r in out if r[2] is not None and r[4] is not None)))


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("fetch", "build"):
        die("usage: make_radii_data.py fetch | build")
    fetch() if sys.argv[1] == "fetch" else build()
