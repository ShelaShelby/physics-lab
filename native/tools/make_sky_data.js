// Copies the night-sky data (SKY), the far-away things (FAR), the Voyagers (FAR_PROBES) and
// Earth's land outlines (EARTH_LAND) out of the web version (index.html) into
// native/src/orbit/sky_data.inc and native/src/render/earth_land.inc.
// Sources (see the web version): HYG database v4.1 (Hipparcos) stars, Stellarium modern
// constellation lines (both CC BY-SA 4.0); far-away things from HYG and Wikipedia.
// Run from the repository root:   node native/tools/make_sky_data.js
'use strict';
const fs = require('fs'), path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../../index.html'), 'utf8');
const line = start => { const at = html.indexOf(start); if (at < 0) throw new Error('missing ' + start); return html.slice(at, html.indexOf('\n', at)); };
const skyLine = line('const SKY = {');
const SKY = eval('(' + skyLine.slice(skyLine.indexOf('{'), skyLine.lastIndexOf('}') + 1) + ')');
const farLine = line('const FAR = [');
const FAR = eval(farLine.slice(farLine.indexOf('['), farLine.indexOf('], FAR_PROBES') + 1));
const PROBES = eval(farLine.slice(farLine.indexOf('FAR_PROBES = ') + 13, farLine.lastIndexOf(']') + 1));

const q = s => JSON.stringify(s);
const chunks = (s, n) => { const out = []; for (let i = 0; i < s.length; i += n) out.push(s.slice(i, i + n)); return out; };
const o = [];
o.push('// Generated by native/tools/make_sky_data.js from index.html. Do not edit by hand.');
o.push('// Stars: 10 characters each in base 36: ecliptic longitude (0.01°), latitude + 90° (0.01°), magnitude + 2 (0.1), colour B−V + 0.5 (0.02).');
o.push('static const char* const kSkyStars =\n' + chunks(SKY.stars, 2000).map(c => '    ' + q(c)).join('\n') + ';');
o.push('// Constellation lines: per constellation, pairs of star indices (3 + 3 characters, base 36).');
o.push('static const char* const kSkyLines[] = {\n' + SKY.lines.map(l => '    ' + q(l) + ',').join('\n') + '\n};');
o.push('struct SkyConstellation { const char* name; double lon, lat; };   // where its name goes (deg)');
o.push('static const SkyConstellation kSkyCons[] = {\n' + SKY.cons.map(c => `    {${q(c[0])}, ${c[1]}, ${c[2]}},`).join('\n') + '\n};');
o.push('struct SkyName { int star; const char* name; };');
o.push('static const SkyName kSkyNames[] = {\n' + SKY.names.map(n => `    {${n[0]}, ${q(n[1])}},`).join('\n') + '\n};');
o.push(`static const double kGalCentre[2] = {${SKY.gcen[0]}, ${SKY.gcen[1]}};   // ecliptic lon, lat of the galactic centre (deg)`);
o.push(`static const double kGalPole[2] = {${SKY.gpole[0]}, ${SKY.gpole[1]}};     // ecliptic lon, lat of the north galactic pole (deg)`);
o.push('// Far-away things: real direction (ecliptic lon, lat, deg) and distance (light years)');
o.push('static const FarData kFar[] = {\n' + FAR.map(f => `    {${q(f.key)}, ${q(f.name)}, ${q(f.kind)}, ${f.lon}, ${f.lat}, ${f.ly}, ${q(f.sp)}, ${q(f.con)},\n     ${q(f.note)}},`).join('\n') + '\n};');
o.push('// The Voyagers: direction (deg) and distance (AU) on 30 Sep 2026, speed away from the Sun (km/s), launch year, heliopause crossing (AU, year)');
o.push('static const ProbeData kProbes[] = {\n' + PROBES.map(f => `    {${q(f.key)}, ${q(f.name)}, ${f.lon}, ${f.lat}, ${f.au}, ${f.kms}, ${f.year}, ${f.cross}, ${f.crossYear}},`).join('\n') + '\n};');
fs.writeFileSync(path.join(__dirname, '../src/orbit/sky_data.inc'), o.join('\n') + '\n');

// Earth's land: Natural Earth 110 m outlines, in half-degrees, delta-coded (polygons split by ';')
const landLine = line('const EARTH_LAND = "');
const land = landLine.slice(landLine.indexOf('"') + 1, landLine.lastIndexOf('"'));
fs.writeFileSync(path.join(__dirname, '../src/render/earth_land.inc'),
  '// Generated by native/tools/make_sky_data.js from index.html (EARTH_LAND). Natural Earth 110 m land outlines (public domain),\n' +
  '// in half-degrees: each polygon is "lon,lat" then steps "dlon,dlat"; polygons are separated by ";".\n' +
  'static const char* const kEarthLand =\n' + chunks(land, 2000).map(c => '    ' + q(c)).join('\n') + ';\n');
console.log(`stars ${SKY.stars.length / 10}, constellations ${SKY.lines.length}, names ${SKY.names.length}, far ${FAR.length}, probes ${PROBES.length}`);
