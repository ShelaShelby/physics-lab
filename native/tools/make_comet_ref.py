#!/usr/bin/env python3
"""Makes native/tests/reference/comet_table.inc: for each of the six comets of the Orbit Lab,
 (1) the orbit record its elements come from, read from JPL's Small-Body Database API (67P: see below), and
 (2) Horizons heliocentric position vectors (ecliptic and equinox of J2000, km, TDB) at two dates:
     the record's perihelion time (tp) and 2026-01-01 12:00 TDB (JD 2461042.0, the app's reference epoch).
The test (tests/test_orbit.cpp, section 15) checks that src/orbit/solar_data.cpp holds exactly the record's elements, and measures the lab's position against the Horizons vectors.

Sources (all read by this script; network needed):
  SBDB API   https://ssd-api.jpl.nasa.gov/sbdb.api?sstr=<name>&full-prec=1   (orbit_id, epoch, elements q e i om w tp per)
  Horizons   https://ssd.jpl.nasa.gov/api/horizons.api  COMMAND='DES=<des>;CAP'  EPHEM_TYPE=VECTORS, CENTER='@10', REF_PLANE='ECLIPTIC', OUT_UNITS='KM-S', VEC_TABLE='1', TLIST=<jd jd>
67P is the exception: SBDB's current record (orbit K284/1) has its epoch in 2015 (JD 2457305.5), and as a fixed two-body orbit it is 1.37 AU off Horizons in Nov 2021 and 0.15 AU in Jan 2026.
The same orbit solution K284/1 osculating at 2021-11-02 00:00 TDB (the 2021 perihelion), asked from Horizons with EPHEM_TYPE=ELEMENTS, TLIST=2459520.5, is 0.011 AU off in Jan 2026; it is used instead (one orbit solution, one epoch).
Usage: python3 native/tools/make_comet_ref.py > native/tests/reference/comet_table.inc
"""
import datetime, json, subprocess, sys, urllib.parse

AU_KM = 149597870.7   # IAU 2012 au, km (JPL astro_par page)
COMETS = [  # lab name, SBDB search string, Horizons COMMAND, element source
    ("Halley", "1P", "DES=1P;CAP", "sbdb"),
    ("Hale–Bopp", "C/1995 O1", "DES=C/1995 O1;CAP", "sbdb"),
    ("NEOWISE", "C/2020 F3", "DES=C/2020 F3;CAP", "sbdb"),
    ("Encke", "2P", "DES=2P;CAP", "sbdb"),
    ("67P", "67P", "DES=67P;CAP", "hz-elements:2459520.5"),
    ("Swift–Tuttle", "109P", "DES=109P;CAP", "sbdb"),
]
JD_B = 2461042.0


def get(url, params):
    full = url + "?" + urllib.parse.urlencode(params)
    return subprocess.run(["curl", "-sS", "-m", "90", full], capture_output=True, text=True, check=True).stdout


def jd_text(jd):
    return (datetime.datetime(2000, 1, 1, 12) + datetime.timedelta(days=jd - 2451545.0)).strftime("%Y-%m-%d %H:%M")


def sbdb(name):
    d = json.loads(get("https://ssd-api.jpl.nasa.gov/sbdb.api", {"sstr": name, "full-prec": "1"}))
    o = d["orbit"]
    el = {e["name"]: float(e["value"]) for e in o["elements"]}
    return dict(record=str(o["orbit_id"]), epoch=float(o["epoch"]), soln=o.get("soln_date", "?"), q=el["q"], e=el["e"], i=el["i"], om=el["om"], w=el["w"], tp=el["tp"], per=el["per"])


def hz_elements(des, jd):
    t = get("https://ssd.jpl.nasa.gov/api/horizons.api", {"format": "text", "COMMAND": "'%s'" % des, "OBJ_DATA": "NO", "MAKE_EPHEM": "YES", "EPHEM_TYPE": "ELEMENTS", "CENTER": "'@10'",
                                                          "TLIST": "'%r'" % jd, "REF_PLANE": "'ECLIPTIC'", "OUT_UNITS": "'AU-D'", "CSV_FORMAT": "'YES'"})
    src = [l for l in t.splitlines() if l.startswith("Target body name")][0]
    rec = src.split("JPL#")[1].split("}")[0]
    row = [x.strip() for x in t.split("$$SOE")[1].split("$$EOE")[0].strip().split(",")]
    # JDTDB, Calendar, EC, QR, IN, OM, W, Tp, N, MA, TA, A, AD, PR
    return dict(record=rec, epoch=float(row[0]), soln="Horizons ELEMENTS", q=float(row[3]), e=float(row[2]), i=float(row[4]), om=float(row[5]), w=float(row[6]), tp=float(row[7]), per=float(row[13]))


def hz_vectors(des, jds):
    t = get("https://ssd.jpl.nasa.gov/api/horizons.api", {"format": "text", "COMMAND": "'%s'" % des, "OBJ_DATA": "NO", "MAKE_EPHEM": "YES", "EPHEM_TYPE": "VECTORS", "CENTER": "'@10'",
                                                          "TLIST": "'%s'" % " ".join("%r" % j for j in jds), "REF_PLANE": "'ECLIPTIC'", "VEC_TABLE": "'1'", "OUT_UNITS": "'KM-S'", "CSV_FORMAT": "'YES'"})
    rows = []
    for l in t.split("$$SOE")[1].split("$$EOE")[0].strip().splitlines():
        p = [x.strip() for x in l.split(",")]
        rows.append((float(p[0]), float(p[2]), float(p[3]), float(p[4])))
    return rows


print("// Generated by native/tools/make_comet_ref.py. Do not edit by hand. Retrieved %s." % datetime.date.today().isoformat())
print("// Record = the orbit solution the lab's elements come from (JPL SBDB orbit_id; 67P: Horizons ELEMENTS of the same solution K284/1, see the tool). epoch, tp: Julian day (TDB). q (au), e, i, om, w (deg), per (days).")
print("// Vectors: JPL Horizons, heliocentric, ecliptic and mean equinox of J2000, km, TDB. Query: COMMAND='DES=<des>;CAP' EPHEM_TYPE=VECTORS CENTER='@10' REF_PLANE='ECLIPTIC' VEC_TABLE='1' OUT_UNITS='KM-S' TLIST='<tp> 2461042.0'.")
print("struct CometRecord { const char* name; const char* record; const char* soln; double epoch, q, e, i, om, w, tp, per; double jd[2], x[2], y[2], z[2]; };")
print("static const CometRecord kCometRecords[] = {")
for name, sstr, des, how in COMETS:
    r = hz_elements(des, float(how.split(":")[1])) if how.startswith("hz-elements") else sbdb(sstr)
    jds = [round(r["tp"], 3), JD_B]
    v = hz_vectors(des, jds)
    print("    // %s: record %s (%s), epoch JD %.1f = %s; Horizons vectors at %s and %s" % (name, r["record"], r["soln"], r["epoch"], jd_text(r["epoch"]), jd_text(jds[0]), jd_text(jds[1])))
    print('    {"%s", "%s", "%s", %r, %r, %r, %r, %r, %r, %r, %r,' % (name, r["record"], r["soln"], r["epoch"], r["q"], r["e"], r["i"], r["om"], r["w"], r["tp"], r["per"]))
    print("     {%r, %r}, {%r, %r}, {%r, %r}, {%r, %r}}," % (v[0][0], v[1][0], v[0][1], v[1][1], v[0][2], v[1][2], v[0][3], v[1][3]))
print("};")
