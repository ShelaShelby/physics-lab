#!/usr/bin/env python3
"""Draws the Physics Lab icon (an atom: a nucleus and three orbits with electrons) and writes
   assets/physics_lab.ico (16, 24, 32, 48, 64, 128, 256 px, PNG inside) and src/ui/icon_data.inc (64 px RGBA, for the window).
   Needs Pillow.  Run from the repository root:   python3 native/tools/make_icon.py"""
import math, os, struct, io
from PIL import Image, ImageDraw

def draw(size):
    S = size * 4                                   # draw 4x bigger, then shrink: smooth edges
    im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, S - 1, S - 1], radius=S * 0.22, fill=(18, 24, 44, 255))
    c = S / 2
    for k, ang in enumerate((0, 60, 120)):
        pts = []
        for i in range(181):
            t = i / 180 * 2 * math.pi
            x, y = S * 0.40 * math.cos(t), S * 0.15 * math.sin(t)
            a = math.radians(ang)
            pts.append((c + x * math.cos(a) - y * math.sin(a), c + x * math.sin(a) + y * math.cos(a)))
        d.line(pts + pts[:1], fill=(110, 170, 255, 255), width=max(2, int(S * 0.028)), joint='curve')
        t = (0.35 + 0.31 * k) * 2 * math.pi         # an electron on each orbit
        x, y = S * 0.40 * math.cos(t), S * 0.15 * math.sin(t)
        a = math.radians(ang)
        ex, ey = c + x * math.cos(a) - y * math.sin(a), c + x * math.sin(a) + y * math.cos(a)
        r = S * 0.052
        d.ellipse([ex - r, ey - r, ex + r, ey + r], fill=(255, 255, 255, 255))
    r = S * 0.095
    d.ellipse([c - r, c - r, c + r, c + r], fill=(255, 168, 40, 255))
    return im.resize((size, size), Image.LANCZOS)

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sizes = [16, 24, 32, 48, 64, 128, 256]
pngs = []
for s in sizes:
    b = io.BytesIO(); draw(s).save(b, 'PNG'); pngs.append(b.getvalue())
ico = struct.pack('<HHH', 0, 1, len(sizes))
off = 6 + 16 * len(sizes)
for s, p in zip(sizes, pngs):
    ico += struct.pack('<BBBBHHII', s % 256, s % 256, 0, 0, 1, 32, len(p), off)
    off += len(p)
ico += b''.join(pngs)
open(os.path.join(root, 'assets', 'physics_lab.ico'), 'wb').write(ico)
rgba = draw(64).tobytes()
lines = ['// Generated by native/tools/make_icon.py. Do not edit by hand.', '// The window icon: 64 x 64 pixels, RGBA, top row first.', 'static const unsigned char kIconRgba[64 * 64 * 4] = {']
for i in range(0, len(rgba), 32):
    lines.append('    ' + ','.join(str(v) for v in rgba[i:i + 32]) + ',')
lines.append('};')
open(os.path.join(root, 'src', 'ui', 'icon_data.inc'), 'w').write('\n'.join(lines) + '\n')
draw(256).save('/tmp/icon256.png')
print('wrote', len(ico), 'bytes of .ico')
