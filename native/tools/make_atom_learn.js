// Copies the Atom Lab timeline (LRN_TL) out of the web version into native/src/atom/atom_learn_data.inc.
// Run from the repository root:   node native/tools/make_atom_learn.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAtomWeb} = require('../tests/reference/atom_web.js');
const {W} = loadAtomWeb();
const q = s => JSON.stringify(String(s));
const o = ['// Generated by native/tools/make_atom_learn.js from index.html. Do not edit by hand.'];
o.push('static const TimelineStep kTl[] = {');
for (const e of W.LRN_TL) {
  const set = e.lab ? Object.entries(e.lab[1]).map(([k, v]) => `{${q(k)}, ${q(v)}}`).join(', ') : '';
  o.push(`    {${q(e.y)}, ${q(e.who)}, ${q(e.t)}, ${q(e.d)},\n     ${q(e.svg)},\n     ${q(e.lab ? e.lab[0] : '')}, {${set}}},`);
}
o.push('};');
fs.writeFileSync(path.join(__dirname, '../src/atom/atom_learn_data.inc'), o.join('\n') + '\n');
// the web Atom Lab's own update history, for the native changelog window
const c = ['// Generated by native/tools/make_atom_learn.js from index.html (SIMS[\'Atom Lab\'].changelog). Do not edit by hand.'];
W.SIM.changelog.forEach(([v, t, d]) => c.push(`{${q(v)}, ${q(t)}, ${q(d)}},`));
fs.writeFileSync(path.join(__dirname, '../src/ui/web_atom_changelog.inc'), c.join('\n') + '\n');
fs.writeFileSync(path.join(__dirname, '../src/ui/web_atom_changelog_note.inc'), '// Generated by native/tools/make_atom_learn.js from index.html. Do not edit by hand.\n' + q(W.SIM.changelogNote) + '\n');
console.log('wrote atom_learn_data.inc,', W.LRN_TL.length, 'steps');
