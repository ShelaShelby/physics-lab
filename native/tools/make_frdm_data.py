#!/usr/bin/env python3
"""0.46.3: the calculated ground-state quadrupole deformation beta2 of FRDM(2012) -> src/atom/frdm_data.inc.
Source: P. Moller, A. J. Sierk, T. Ichikawa, H. Sagawa, "Nuclear ground-state masses and deformations: FRDM(2012)", Atomic Data and Nuclear Data Tables
109-110 (2016) 1-204, arXiv:1508.06294 (data/frdm2012/, the PDF as downloaded). Its table lists, under each "Z = n (Sym)" heading, rows
"N A eps2 eps3 eps4 eps6 beta2 beta3 beta4 beta6 ...": column 7 is beta2. Needs pdftotext (poppler-utils); run: python3 -I native/tools/make_frdm_data.py"""
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pl_sources   # the PDF is in the private sources repo (PL_SOURCES_DIR)
here = os.path.dirname(os.path.abspath(__file__))
pdf = pl_sources.path("frdm2012/moller_2016_frdm2012_arxiv1508.06294.pdf")
txt = subprocess.run(["pdftotext", "-layout", pdf, "-"], capture_output=True, text=True, check=True).stdout.replace("−", "-")
num = r"-?\d+\.\d+"
rowre = re.compile(r"^\s*(\d+)\s+(\d+)\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s+(" + num + r")\s")
z = None
rows = {}
for line in txt.split("\n"):
    m = re.match(r"^\s*Z = (\d+) \(", line)
    if m:
        z = int(m.group(1)); continue
    m = rowre.match(line)
    if m and z is not None:
        n, a = int(m.group(1)), int(m.group(2))
        zz = a - n                                     # Z from the row itself (the headings of Z = 113 and up use other symbols)
        if zz < 8 or zz > 136:
            continue                                   # not a table row: skipped
        rows[(zz, a)] = float(m.group(7))
if len(rows) != 9318:   # the paper's table: 9,318 nuclei
    sys.exit("only %d rows parsed" % len(rows))
out = ["// Generated by tools/make_frdm_data.py from data/frdm2012/ (Moller, Sierk, Ichikawa, Sagawa, ADNDT 109-110 (2016) 1, arXiv:1508.06294). Do not edit.",
       "// {Z, A, beta2}: the calculated ground-state quadrupole deformation; %d nuclei." % len(rows)]
for (zz, aa), b in sorted(rows.items()):
    out.append("    {%d, %d, %.3f}," % (zz, aa, b))
open(os.path.join(here, "..", "src", "atom", "frdm_data.inc"), "w").write("\n".join(out) + "\n")
print(len(rows), "rows; Z range", min(k[0] for k in rows), max(k[0] for k in rows))
