#!/usr/bin/env python3
"""Fetch AME2020 and write the table the chart's BINDING-ENERGY height (0.11 stage 4) is built from.

Python 3, standard library only. Run from anywhere:
    python3 native/tools/make_ame_data.py fetch    (needs network: www-nds.iaea.org; writes native/data/ame/mass.mas20.txt)
    python3 native/tools/make_ame_data.py build    (offline: reads that file and src/atom/atom_data.inc, writes src/atom/ame_data.inc)

fetch : one plain GET of  https://www-nds.iaea.org/amdc/ame2020/mass.mas20.txt  (AMDC / IAEA Nuclear Data Section), saved exactly as received.
build : for every nuclide of the file with Z >= 1 (the free neutron, Z = 0, is left out) writes Z, N, the BINDING ENERGY/A in keV, its uncertainty in keV and whether the value is an ESTIMATE.
        The file's own header says: "# in a place of decimal point : estimated (non-experimental) value" and "* in a place of value : the not calculable quantity". So a value written with a
        '#' (for example 8106#) is an estimate (the evaluators' extrapolation from systematics), anything else is derived from measured masses. Nothing is invented: a cell is what the file says.
        Reading: the file's format line is a1,i3,i5,i5,i5,1x,a3,a4,1x,f14.6,... but the real column ends are a character or two off it, so the fields after the element are read as
        whitespace-separated tokens: mass excess, its uncertainty, BINDING ENERGY/A, its uncertainty (the '#' and '*' marks stay attached to their value). N = [4:9], Z = [9:14], A = [14:19].
        The tool also checks that the nuclides are EXACTLY the lab's 3,557 (src/atom/atom_data.inc) and refuses to build otherwise.
"""
import hashlib
import math
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                                     # native/
DATA = os.path.join(ROOT, "data", "ame")
SRC = os.path.join(DATA, "mass.mas20.txt")
LAB = os.path.join(ROOT, "src", "atom", "atom_data.inc")
OUT_INC = os.path.join(ROOT, "src", "atom", "ame_data.inc")
URL = "https://www-nds.iaea.org/amdc/ame2020/mass.mas20.txt"


def die(msg):
    sys.exit("make_ame_data.py: " + msg)


def fetch():
    req = urllib.request.Request(URL, headers={"User-Agent": "PhysicsLab-native-data-tool"})
    with urllib.request.urlopen(req, timeout=120) as r:
        body = r.read()
        print("HTTP", r.status, r.headers.get("Content-Type"), "Last-Modified:", r.headers.get("Last-Modified"))
    os.makedirs(DATA, exist_ok=True)
    with open(SRC, "wb") as f:
        f.write(body)
    print("wrote", SRC, len(body), "bytes, %d lines, sha256 %s" % (body.count(b"\n"), hashlib.sha256(body).hexdigest()))


def lab_nuclides():
    t = open(LAB, encoding="utf-8").read()
    m = re.search(r"kNucLines\[118\] = \{(.*?)\};", t, re.S)
    out = set()
    for line in re.findall(r'"([^"]*)"', m.group(1)):
        z, rest = line.split("|")
        for e in rest.split(","):
            out.add((int(z), int(e.split(":")[0])))
    return out


def cell(s):
    """-> (value, estimated); a '*' means not calculable."""
    s = s.strip()
    if s == "*" or s == "":
        return (float("nan"), False)
    return (float(s.replace("#", ".")), "#" in s)


def build():
    rows = []
    with open(SRC, encoding="ascii") as f:
        for line in f:
            if len(line) < 80 or line[0] not in " 01":
                continue
            try:
                N, Z, A = int(line[4:9]), int(line[9:14]), int(line[14:19])
            except ValueError:
                continue
            if Z == 0:
                continue
            if A != Z + N:
                die("A != Z + N in: " + line[:40])
            tok = line[28:].split()
            b, est = cell(tok[2])
            u, _ = cell(tok[3])
            if math.isnan(b):
                die("a binding energy that is not calculable: %d %d" % (Z, N))
            rows.append((Z, N, b, u, est))
    rows.sort()
    if len({(r[0], r[1]) for r in rows}) != len(rows):
        die("a nuclide appears twice")
    got = {(r[0], r[1]) for r in rows}
    lab = lab_nuclides()
    if got != lab:
        die("the nuclides are not the lab's: %d only here, %d only in the lab" % (len(got - lab), len(lab - got)))
    with open(OUT_INC, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by native/tools/make_ame_data.py from data/ame/mass.mas20.txt (AME2020). Do not edit by hand.\n")
        f.write("// Citation, as the file gives it: W.J. Huang, M. Wang, F.G. Kondev, G. Audi and S. Naimi, Chin. Phys. C45, 030002 (2021) (AME2020 I); M. Wang, W.J. Huang, F.G. Kondev, G. Audi and S. Naimi, Chin. Phys. C45, 030003 (2021) (II).\n")
        f.write("// %d nuclides (the free neutron left out): Z, N, binding energy per nucleon (keV), its uncertainty (keV), 1 = an estimate (the file marks it with # in place of the decimal point).\n" % len(rows))
        f.write("static const AmeRow kAme[] = {\n")
        for z, n, b, u, est in rows:
            f.write("    {%d, %d, %s, %s, %d},\n" % (z, n, repr(b), repr(u) if not math.isnan(u) else "NAN", 1 if est else 0))
        f.write("};\n")
    meas = [r for r in rows if not r[4]]
    top = max(meas, key=lambda r: r[2])
    print("wrote", OUT_INC, len(rows), "rows;", len(meas), "measured,", len(rows) - len(meas), "estimated; highest measured:", top[:3], "; heaviest measured Z:", max(r[0] for r in meas))


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("fetch", "build"):
        die("usage: make_ame_data.py fetch|build")
    fetch() if sys.argv[1] == "fetch" else build()
