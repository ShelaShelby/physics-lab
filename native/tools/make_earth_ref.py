#!/usr/bin/env python3
"""Download the Earth's position seen from the Sun's centre from JPL Horizons and write native/tests/reference/earth_table.inc (0.10.4 stage 2).

Python 3, standard library only. Needs the internet (ssd.jpl.nasa.gov). Run from anywhere:  python3 native/tools/make_earth_ref.py

What is asked (Horizons API, https://ssd-api.jpl.nasa.gov/doc/horizons.html), the same epochs, frame and method as make_jpl_data.py / make_moon_ref.py:
    COMMAND = '399' (Earth, the planet's own centre, NOT the Earth-Moon barycentre '3')   CENTER = '500@10' (the Sun's centre, "heliocentric")
    EPHEM_TYPE = VECTORS, VEC_TABLE = 1 (position only)   VEC_CORR = NONE (geometric)   REF_PLANE = ECLIPTIC (ecliptic and mean equinox of J2000)
    OUT_UNITS = KM-S   TIME_TYPE = TDB   START 1800-01-01 12:00, STOP 2100-01-01 12:00, STEP 1 y (301 rows, 1 January 12:00 TDB of every year)
The reply must say {source: DE441} (the same ephemeris as the other tables). A reply that is an error page, is incomplete, or does not say what is expected stops the
tool (nothing is written). The Sun here is Horizons' Sun body (10), which is what the other heliocentric tests subtract too (planet minus Sun).
"""
import os
import re
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                                   # native/
OUT = os.path.join(ROOT, "tests", "reference", "earth_table.inc")
API = "https://ssd.jpl.nasa.gov/api/horizons.api"
NUM = r"[-+]?\d\.\d+E[-+]\d\d"
RE_ROW = re.compile(r"^\s*(\d+\.\d+),\s*A\.D\. (\d{4})-Jan-01 12:00:00\.\d+,\s*(%s),\s*(%s),\s*(%s),\s*$" % (NUM, NUM, NUM))


def die(msg):
    sys.exit("make_earth_ref.py: " + msg)


def jd_noon(year):
    """Julian date of 1 January 12:00 of a Gregorian year (integer arithmetic, as in make_jpl_data.py)."""
    a = 1
    y = year + 4800 - a
    m = 1 + 12 * a - 3
    return 1 + (153 * m + 2) // 5 + 365 * y + y // 4 - y // 100 + y // 400 - 32045


def times_1000(s):
    mant, exp = s.upper().split("E")
    return "%sE%+03d" % (mant, int(exp) + 3)


def main():
    params = [("format", "text"), ("COMMAND", "'399'"), ("CENTER", "'500@10'"), ("MAKE_EPHEM", "YES"), ("EPHEM_TYPE", "VECTORS"),
              ("START_TIME", "'1800-01-01 12:00'"), ("STOP_TIME", "'2100-01-01 12:00'"), ("STEP_SIZE", "'1 y'"), ("REF_PLANE", "ECLIPTIC"),
              ("OUT_UNITS", "KM-S"), ("VEC_TABLE", "1"), ("VEC_CORR", "NONE"), ("TIME_TYPE", "TDB"), ("CSV_FORMAT", "YES")]
    url = API + "?" + urllib.parse.urlencode(params, quote_via=urllib.parse.quote)
    try:
        text = urllib.request.urlopen(url, timeout=120).read().decode("utf-8")
    except Exception as e:                                      # noqa: BLE001
        die("Horizons not reachable (%s)" % e)
    lines = text.replace("\r\n", "\n").split("\n")
    flat = [re.sub(r"\s+", " ", l).strip() for l in lines]
    if "$$SOE" not in flat or "$$EOE" not in flat:
        die("no $$SOE ... $$EOE block (error page?):\n" + text[:600])
    head = flat[:flat.index("$$SOE")]

    def need(prefix, part):
        for l in head:
            if l.startswith(prefix):
                if part not in l:
                    die("header line '%s' should contain '%s'" % (l, part))
                return
        die("header line starting '%s' is missing" % prefix)
    need("Target body name:", "Earth (399)")
    need("Target body name:", "{source: DE441}")
    need("Center body name:", "Sun (10)")
    need("Center-site name:", "BODY CENTER")
    need("Output units", "KM-S")
    need("Output type", "GEOMETRIC cartesian states")
    need("Reference frame", "Ecliptic of J2000.0")
    body = [l for l in lines[flat.index("$$SOE") + 1:flat.index("$$EOE")] if l.strip()]
    if len(body) != 301:
        die("%d rows, expected 301" % len(body))
    rows = []
    for i, l in enumerate(body):
        m = RE_ROW.match(l)
        if not m:
            die("row not understood: " + l)
        if int(m.group(2)) != 1800 + i or float(m.group(1)) != jd_noon(1800 + i):
            die("row %d: year/Julian date %s %s, expected %d %d" % (i, m.group(2), m.group(1), 1800 + i, jd_noon(1800 + i)))
        rows.append((m.group(1), [times_1000(m.group(k)) for k in (3, 4, 5)]))
    mm = re.search(r"API_USER \w+ (\w+) +(\d+) [\d:]+ (\d{4})", text)
    date = (mm.group(3) + "-" + mm.group(1) + "-" + mm.group(2)) if mm else "unknown"
    with open(OUT, "w", newline="\n") as f:
        f.write("// GENERATED by native/tools/make_earth_ref.py; do not edit. Source: NASA/JPL Horizons API (https://ssd.jpl.nasa.gov/api/horizons.api), Earth (399) {source: DE441}.\n")
        f.write("// Retrieved (date in the reply header): %s. Query, as made:\n//   %s\n" % (date, url))
        f.write("// Initialiser for  double kEarthTable[301][4]: { Julian date (TDB), x, y, z (m) }: the Earth's centre seen from the Sun's centre (500@10), ecliptic and mean equinox of J2000, geometric,\n")
        f.write("// 1 January 12:00 TDB of every year 1800 .. 2100. Metres = km x 1000: the digits are exactly Horizons', only the exponent is raised by 3.\n{\n")
        for jd, v in rows:
            f.write("{%s, %s},\n" % (jd, ", ".join(v)))
        f.write("}\n")
    print("wrote %s (%d rows, retrieved %s, %d bytes)" % (OUT, len(rows), date, os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
