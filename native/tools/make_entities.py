#!/usr/bin/env python3
"""0.15 stage 2, C1: writes src/app/html_entities_data.inc from the HTML Standard's named character references (entities.json).
usage: make_entities.py <entities.json> > src/app/html_entities_data.inc
Source: https://html.spec.whatwg.org/entities.json (the standard's own host was not reachable from the cloud session; the same file was read on 2026-10-05 from
https://raw.githubusercontent.com/w3c/html/master/entities.json, 2,231 entries, sha256 printed below). Only the names that end in ';' are kept (the legacy
forms without ';' are not decoded: a missing ';' stays text)."""
import json, sys, hashlib
raw = open(sys.argv[1], 'rb').read()
d = json.loads(raw)
rows = []
for k, v in d.items():
    if not k.endswith(';'): continue
    cps = v['codepoints']
    assert 1 <= len(cps) <= 2
    rows.append((k[1:-1], cps[0], cps[1] if len(cps) == 2 else 0))
rows.sort()                                   # byte order of the names, for the binary search in html_entities.cpp
print('// GENERATED by tools/make_entities.py from the HTML Standard\'s entities.json (sha256 %s). Do not edit.' % hashlib.sha256(raw).hexdigest())
print('// %d named character references ending in ";": name (without & and ;), first code point, second code point (0 = none). Sorted by name.' % len(rows))
for n, a, b in rows:
    print('{"%s", 0x%X, 0x%X},' % (n, a, b))
