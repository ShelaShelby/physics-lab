#!/usr/bin/env python3
"""0.46.3: NIST-JANAF log Kf of the monatomic gases H, N, O, F, Cl, Br, I (data/janaf/*.txt, saved as received) -> src/atom/janaf_data.inc.
log Kf is the formation of one X(g) from the element's reference state (X2 gas where the element is a gas), so X2 <-> 2X has Kp = Kf^2 (src/atom/dissociation.cpp)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
files = [(1, "H-001"), (7, "N-002"), (8, "O-001"), (9, "F-001"), (17, "Cl-001"), (35, "Br-001"), (53, "I-001")]
out = ["// Generated by tools/make_janaf_data.py from data/janaf/*.txt (NIST-JANAF Thermochemical Tables, janaf.nist.gov, read 2026-11-08). Do not edit.",
       "// {Z, T (K), log10 Kf of X(g)}, every row of each table from 298.15 K up."]
for z, f in files:
    for line in open(os.path.join(here, "..", "data", "janaf", f + ".txt")):
        c = line.rstrip("\n").split("\t")
        try:
            t, lk = float(c[0]), float(c[7])
        except (ValueError, IndexError):
            continue
        if t >= 298.15:
            out.append("    {%d, %s, %s}," % (z, c[0], c[7]))
open(os.path.join(here, "..", "src", "atom", "janaf_data.inc"), "w").write("\n".join(out) + "\n")
