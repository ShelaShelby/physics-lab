#!/usr/bin/env python3
"""0.96.0 (outside review of 28 Nov 2026, part E): download the Moon's position seen from the Earth's centre from JPL Horizons at dates OUTSIDE 1800 to 1 Jan 2100,
and write native/tests/reference/moon_outside_table.inc. tests/test_moon.cpp testEllipse measures the fitted ellipse (orbit/moon_elp.h moonGeocentricEllipse) against it.

Python 3, standard library only. Needs the internet (ssd.jpl.nasa.gov). Run from anywhere:  python3 native/tools/make_moon_outside_ref.py
The query is make_moon_ref.py's (its query, parse and times_1000 are used): COMMAND '301', CENTER '500@399', VECTORS, geometric, ecliptic and mean equinox of J2000,
KM-S, TDB, DE441 (each reply's header is checked). Three groups:
    group 0: every 5 years, 1 January 12:00 TDB, 1600 .. 1795 (40 rows)
    group 1: daily at 12:00 TDB, 2 Jan 2100 .. 31 Dec 2100 (364 rows): the part of the date box's range (to 31 Dec 2100) after ELP's span ends (1 Jan 2100 12:00 TDB)
    group 2: every 5 years, 1 January 12:00 TDB, 2105 .. 2300 (40 rows)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_moon_ref as mr  # noqa: E402

OUT = os.path.join(mr.ROOT, "tests", "reference", "moon_outside_table.inc")
GROUPS = [
    (0, "1600-01-01 12:00", "1795-01-01 12:00", "5 y", 40),
    (1, "2100-01-02 12:00", "2100-12-31 12:00", "1 d", 364),
    (2, "2105-01-01 12:00", "2300-01-01 12:00", "5 y", 40),
]


def main():
    rows, urls, got = [], [], set()
    for group, start, stop, step, n in GROUPS:
        url, text = mr.query("301", start, stop, step)
        r, d = mr.parse(text, "Moon (301)", start, n, "group %d" % group)
        urls.append(url)
        got.add(d)
        print("group %d ok: %d rows %s .. %s" % (group, len(r), r[0][1], r[-1][1]))
        rows += [(group, jd, [mr.times_1000(v) for v in xyz]) for jd, _, xyz in r]
    if len(got) != 1:
        mr.die("replies carry different retrieval dates: %s" % got)
    with open(OUT, "w", newline="\n") as f:
        f.write("// GENERATED by native/tools/make_moon_outside_ref.py; do not edit. Source: NASA/JPL Horizons API (https://ssd.jpl.nasa.gov/api/horizons.api), Moon {source: DE441}.\n")
        f.write("// Retrieved (date in the reply header): %s. Query for each group, as made (one URL each):\n" % got.pop())
        for u in urls:
            f.write("//   %s\n" % u)
        f.write("// Initialiser for  double kMoonOutside[%d][5]: { group, Julian date (TDB), Moon x, y, z (m) }, seen from the Earth's centre (500@399), ecliptic and mean equinox of J2000,\n" % len(rows))
        f.write("// geometric. Metres = km x 1000: the digits are exactly Horizons', only the exponent is raised by 3.\n")
        f.write("// group 0: every 5 years 1600..1795 at 1 January 12:00 TDB (40 rows); group 1: daily 2100-01-02 .. 2100-12-31 at 12:00 TDB (364 rows); group 2: every 5 years 2105..2300 (40 rows).\n{\n")
        for g, jd, m in rows:
            f.write("{%d, %s, %s},\n" % (g, jd, ", ".join(m)))
        f.write("}\n")
    print("wrote %s (%d rows, %d bytes)" % (OUT, len(rows), os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
