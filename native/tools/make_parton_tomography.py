#!/usr/bin/env python3
"""0.44: where the proton's momentum is, by kind of parton and by momentum fraction x (the Accurate quark style's dots).

Method (native/data/qcd/tomography/README.txt has the sources and the numbers read from each):
  Momentum densities x f(x) at mu = 2 GeV: ABM11 NLO, 4 flavours (Alekhin, Bluemlein, Moch, PRD 86, 054009 (2012)), the LHAPDF grid saved as
  received (data/qcd/tomography/abm11_4n_nlo/). The same set and scale as the GPD fit below (Diehl and Kroll, table 9 and section 6.2: NLO, 2 GeV).
  Interpolation: cubic Lagrange in ln Q^2 on the four grid nodes around 2 GeV (all above the charm threshold), then cubic splines in ln x.
Writes native/src/atom/quark_tomo_data.h: on a ln x grid, for each kind (u_v, d_v, u-bar, d-bar, s + c, gluons) x f(x) and the fraction of the
proton's momentum carried below x (cumulative, by kind). The widths (where in b each x sits) are formulas in src/atom/quark_tomo.h, with their sources.
Needs numpy and scipy. Run from the repository root:  python3 native/tools/make_parton_tomography.py
"""
import os
import sys
import numpy as np
from scipy.interpolate import CubicSpline

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pl_sources   # the ABM11 grid is in the private sources repo (PL_SOURCES_DIR)
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
GRID = pl_sources.path("qcd/tomography/abm11_4n_nlo/abm11_4n_nlo_0000.dat")
MU = 2.0                                   # GeV
NX, XMIN = 241, 1e-5                       # output grid: x = 1e-5 .. 1, 48 points per decade; below 1e-5 the momentum share is < 1e-4 (printed)


def load():
    blk = open(GRID).read().split("---")[1].strip().split("\n")
    xs = np.array([float(v) for v in blk[0].split()])
    qs = np.array([float(v) for v in blk[1].split()])
    fl = [int(v) for v in blk[2].split()]
    vals = np.array([[float(v) for v in r.split()] for r in blk[3:]]).reshape(len(xs), len(qs), len(fl))   # x outer, Q inner (lhagrid1)
    return xs, qs, fl, vals


def at_mu(xs, qs, fl, vals):
    i = int(np.searchsorted(qs, MU))       # nodes i-2 .. i+1 around MU
    idx = list(range(i - 2, i + 2))
    assert qs[idx[0]] > 1.27, "an interpolation node is below the charm threshold"
    t = np.log(qs[idx] ** 2); t0 = np.log(MU ** 2)
    w = np.array([np.prod([(t0 - t[k]) / (t[j] - t[k]) for k in range(4) if k != j]) for j in range(4)])
    xf = np.tensordot(vals[:, idx, :], w, axes=([1], [0]))          # (nx, nfl): x f(x) at 2 GeV on the grid's x nodes
    return {f: xf[:, k] for k, f in enumerate(fl)}


def main():
    xs, qs, fl, vals = load()
    xf = at_mu(xs, qs, fl, vals)
    lx = np.log(xs)
    kinds = {"uv": xf[2] - xf[-2], "dv": xf[1] - xf[-1], "ub": xf[-2], "db": xf[-1], "sc": xf[3] + xf[-3] + xf[4] + xf[-4], "g": xf[21]}
    # (each sea flavour: the quark and its antiquark have the same density here; "ub" is the u-bar density, and the sea u quarks have the same)
    sp = {k: CubicSpline(lx, v) for k, v in kinds.items()}
    gx = np.exp(np.linspace(np.log(XMIN), 0, NX))
    fine = np.exp(np.linspace(np.log(1e-7), 0, 40001))
    def integ(k, lo, hi, power):           # integral of x^power f(x) dx = integral of x^power * (x f) d ln x
        m = (fine >= lo) & (fine <= hi)
        y = sp[k](np.log(fine[m])) * fine[m] ** (power - 1) * fine[m]
        return np.trapezoid(y, np.log(fine[m]))
    num = {k: integ(k, 1e-7, 1, 0) for k in ("uv", "dv")}
    mom = {k: integ(k, 1e-7, 1, 1) for k in kinds}
    mom_sea_pairs = {k: (2 if k in ("ub", "db") else 1) * mom[k] for k in kinds}   # u-bar and d-bar: their sea quarks carry as much again
    total = sum(mom_sea_pairs.values())
    print(f"number sum rules: u_v {num['uv']:.4f} (2), d_v {num['dv']:.4f} (1)")
    print("momentum shares at 2 GeV: " + ", ".join(f"{k} {v:.4f}" for k, v in mom_sea_pairs.items()) + f"; total {total:.4f} (1)")
    print("momentum below x = 1e-5: " + ", ".join(f"{k} {integ(k, 1e-7, XMIN, 1):.1e}" for k in kinds))
    out = {}
    for k in kinds:
        f = np.maximum(sp[k](np.log(gx)), 0)      # x f(x) on the output grid (tiny negative wiggles of the grid at x -> 1 set to 0)
        c = np.concatenate([[0], np.cumsum((f[1:] + f[:-1]) / 2 * np.diff(np.log(gx)) * (gx[1:] + gx[:-1]) / 2)])   # momentum carried below x (trapezoid in ln x of x * xf)
        out[k] = (f, c)
    path = os.path.join(ROOT, "src/atom/quark_tomo_data.h")
    def arr(v): return ",".join(f"{a:.9e}" for a in v)
    with open(path, "w") as h:
        h.write("// Generated by native/tools/make_parton_tomography.py (0.44); do not edit. Sources: native/data/qcd/tomography/README.txt\n")
        h.write("// ABM11 NLO 4-flavour parton densities at mu = 2 GeV (LHAPDF grid abm11_4n_nlo, member 0): on x = 1e-5 .. 1 (ln-spaced), x f(x) for u_v, d_v,\n")
        h.write("// u-bar, d-bar (each also the density of the sea quarks of that flavour), s + s-bar + c + c-bar, gluons; and the momentum fraction below x.\n#pragma once\n")
        h.write(f"namespace atom {{\nconstexpr int kTxN = {NX};\nconstexpr double kTxMin = {XMIN};\n")
        for k, (f, c) in out.items():
            h.write(f"constexpr double kTx_{k}[kTxN] = {{{arr(f)}}};\n")
            h.write(f"constexpr double kTxCum_{k}[kTxN] = {{{arr(c)}}};\n")
        h.write("}  // namespace atom\n")
    print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
