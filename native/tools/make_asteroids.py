#!/usr/bin/env python3
"""0.27: the belts' rocks are real asteroids (owner's choice, 5 Nov 2026).

Downloads, from the NASA/JPL Small-Body Database Query API (https://ssd-api.jpl.nasa.gov/sbdb_query.api), the numbered asteroids of three
groups, the brightest (smallest absolute magnitude H, so in practice the largest) first:
  main    classes MBA, IMB, OMB (main belt, inner, outer)     1,800
  trojan  class TJN (Jupiter Trojans)                          300
  kuiper  class TNO (trans-Neptunian objects)                  900
leaving out the dwarf planets the lab draws as bodies of their own (Ceres, Pluto, Haumea, Makemake, Eris).
Saves each reply as received in data/sbdb/ and writes src/orbit/asteroid_data.inc: each rock's osculating elements at its record's epoch.

Run from native/:  python3 tools/make_asteroids.py
"""
import json, os, urllib.parse, urllib.request

API = "https://ssd-api.jpl.nasa.gov/sbdb_query.api"
FIELDS = "full_name,a,e,i,om,w,ma,epoch,n,H,class"
GROUPS = [("main", "MBA,IMB,OMB", 1800), ("trojan", "TJN", 300), ("kuiper", "TNO", 900)]
SKIP = {"Ceres", "Pluto", "Haumea", "Makemake", "Eris"}

here = os.path.dirname(os.path.abspath(__file__))
data_dir = os.path.join(here, "..", "data", "sbdb")
os.makedirs(data_dir, exist_ok=True)
out = ["// GENERATED by native/tools/make_asteroids.py; do not edit. Source: NASA/JPL Small-Body Database Query API, numbered asteroids, brightest (smallest H)",
       "// first, osculating elements at each record's epoch (TDB), full precision. The replies, as received, are in native/data/sbdb/. Queries:"]
rows = []
for key, cls, count in GROUPS:
    q = {"fields": FIELDS, "sb-kind": "a", "sb-ns": "n", "sb-class": cls, "sort": "H", "limit": str(count + len(SKIP)), "full-prec": "1"}
    url = API + "?" + urllib.parse.urlencode(q, safe=",")
    path = os.path.join(data_dir, f"{key}.json")
    if not os.path.exists(path):
        raw = urllib.request.urlopen(url, timeout=120).read()
        open(path, "wb").write(raw)
    reply = json.load(open(path))
    out.append(f"//   {key}: {url}")
    f = reply["fields"]
    taken = 0
    for d in reply["data"]:
        r = dict(zip(f, d))
        name = r["full_name"].strip()
        if any(f" {s} " in f" {name} " for s in SKIP):
            continue
        if taken == count:
            break
        rows.append((key, name, r))
        taken += 1
    assert taken == count, (key, taken)
out.append("// { group (0 main, 1 trojan, 2 kuiper), a (AU), e, i, node, argument of perihelion, mean anomaly (deg), epoch (JD TDB), mean motion (deg/day), H }   // number and name")
out.append("{")
gi = {g[0]: k for k, g in enumerate(GROUPS)}
for key, name, r in rows:
    out.append(f"{{{gi[key]}, {r['a']}, {r['e']}, {r['i']}, {r['om']}, {r['w']}, {r['ma']}, {r['epoch']}, {r['n']}, {r['H']}}},   // {name}")
out.append("}")
open(os.path.join(here, "..", "src", "orbit", "asteroid_data.inc"), "w").write("\n".join(out) + "\n")
print(len(rows), "rocks")
