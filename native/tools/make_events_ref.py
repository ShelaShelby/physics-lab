#!/usr/bin/env python3
"""Makes native/tests/reference/events_table.inc: JPL Horizons values for the Orbit Lab's famous-date checks (0.10.5 stage 5, audit rows 21 and 22).
  (1) vectors of Mars, Jupiter and Saturn as seen from the centre of the Earth, km, ecliptic and mean equinox of J2000, at the two dates of the lab's Jump tiles:
      27 Aug 2003 10:00 TDB (Mars closest to Earth) and 21 Dec 2020 12:00 TDB (Jupiter and Saturn's great conjunction).
      Horizons API: COMMAND='499' / '599' / '699', EPHEM_TYPE=VECTORS, CENTER='500@399', REF_PLANE='ECLIPTIC', VEC_TABLE='1', OUT_UNITS='KM-S', TLIST='<jd>'.
  (2) the two equinoxes of 2026: where the Sun's apparent declination (true equator and equinox of date) crosses zero, from Horizons observer tables of the Sun (COMMAND='10',
      EPHEM_TYPE=OBSERVER, CENTER='500@399', QUANTITIES='2', STEP_SIZE='10 min', 2026-03-20 00:00..2026-03-21 00:00 and 2026-09-22 12:00..2026-09-23 12:00), linear interpolation between rows.
Usage: python3 native/tools/make_events_ref.py > native/tests/reference/events_table.inc   (network needed)
"""
import datetime, re, subprocess, urllib.parse

H = "https://ssd.jpl.nasa.gov/api/horizons.api"


def get(params):
    return subprocess.run(["curl", "-sS", "-m", "90", H + "?" + urllib.parse.urlencode(params)], capture_output=True, text=True, check=True).stdout


def vec(cmd, jd):
    t = get({"format": "text", "COMMAND": "'%s'" % cmd, "OBJ_DATA": "NO", "MAKE_EPHEM": "YES", "EPHEM_TYPE": "VECTORS", "CENTER": "'500@399'", "TLIST": "'%r'" % jd,
             "REF_PLANE": "'ECLIPTIC'", "VEC_TABLE": "'1'", "OUT_UNITS": "'KM-S'", "CSV_FORMAT": "'YES'"})
    p = [x.strip() for x in t.split("$$SOE")[1].split("$$EOE")[0].strip().split(",")]
    return float(p[2]), float(p[3]), float(p[4])


def equinox(start, stop):
    t = get({"format": "text", "COMMAND": "'10'", "OBJ_DATA": "NO", "MAKE_EPHEM": "YES", "EPHEM_TYPE": "OBSERVER", "CENTER": "'500@399'", "START_TIME": "'%s'" % start,
             "STOP_TIME": "'%s'" % stop, "STEP_SIZE": "'10 min'", "QUANTITIES": "'2'", "ANG_FORMAT": "'DEG'", "CSV_FORMAT": "'YES'"})
    rows = []
    for l in t.splitlines():
        if re.match(r"\s*20\d\d-", l):
            p = [x.strip() for x in l.split(",")]
            rows.append((datetime.datetime.strptime(p[0], "%Y-%b-%d %H:%M"), float(p[4])))
    for (t0, d0), (t1, d1) in zip(rows, rows[1:]):
        if d0 * d1 <= 0:
            tt = t0 + (t1 - t0) * (abs(d0) / (abs(d0) + abs(d1)))
            return (tt - datetime.datetime(2000, 1, 1, 12)).total_seconds() / 86400 + 2451545.0
    raise SystemExit("no crossing")


jd_mars = 2452878.5 + 10 / 24.0          # 2003-08-27 10:00
jd_conj = 2459205.0                      # 2020-12-21 12:00
print("// Generated by native/tools/make_events_ref.py. Do not edit by hand. Retrieved %s." % datetime.date.today().isoformat())
print("// JPL Horizons: vectors from the Earth's centre (km, ecliptic and mean equinox of J2000, TDB) and the 2026 equinoxes (Julian day, where the Sun's apparent declination is 0). Queries: see the tool.")
print("struct EventVector { const char* body; double jd, x, y, z; };")
print("static const EventVector kEventVectors[] = {")
for name, cmd, jd in (("Mars", "499", jd_mars), ("Jupiter", "599", jd_conj), ("Saturn", "699", jd_conj)):
    x, y, z = vec(cmd, jd)
    print('    {"%s", %r, %r, %r, %r},' % (name, jd, x, y, z))
print("};")
print("static const double kEquinoxJD[2] = {%r, %r};   // 2026-03-20 and 2026-09-23 (Horizons, TDB)" % (equinox("2026-03-20 00:00", "2026-03-21 00:00"), equinox("2026-09-22 12:00", "2026-09-23 12:00")))
