// NOTE: the committed output was hand-patched after generation (see REPORT 5t). Do not overwrite it by re-running.
// Copies the Atom Lab data out of the web version (index.html) into native/src/atom/atom_data.inc.
// The raw tables (nuclides, decays, binding energies) are copied line by line and parsed in C++
// exactly as the web parses them; the other tables are taken from the web code after it has run.
// Run from the repository root:   node native/tools/make_atom_data.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAtomWeb} = require('../tests/reference/atom_web.js');
const html = fs.readFileSync(path.join(__dirname, '../archive/web/index.html'), 'utf8');
const {W} = loadAtomWeb();
const q = s => JSON.stringify(s);
const num = x => x == null ? 'NAN' : String(x);
const rawLines = name => { const a = html.indexOf('const ' + name + ' = `'), s = html.indexOf('`', a) + 1, e = html.indexOf('`', s); return html.slice(s, e).trim().split('\n'); };
const o = ['// Generated by native/tools/make_atom_data.js from index.html. Do not edit by hand.'];
o.push('static const char* const kName[119] = {' + W.NAME.map(q).join(', ') + '};');
o.push('static const char* const kSymbol[119] = {' + W.SYMBOL.map(q).join(', ') + '};');
o.push('// Every known nuclide, one line per element: "Z|neutrons:code,..." (S stable, U unbound, ? not measured, number = half-life s, ~ approximate)');
o.push('static const char* const kNucLines[118] = {\n' + rawLines('NUC_DATA').map(l => '    ' + q(l) + ',').join('\n') + '\n};');
o.push('// NUBASE2020 decays, one line per element: "Z|neutrons:[half-life/][?]mode=fraction,...;..."');
o.push('static const char* const kDecayLines[118] = {\n' + rawLines('DECAY_DATA').map(l => '    ' + q(l) + ',').join('\n') + '\n};');
o.push('// Binding energy per nucleon (keV), one line per element: "Z|first neutron count|values,..."');
o.push('static const char* const kBeaLines[118] = {\n' + rawLines('BEA_DATA').map(l => '    ' + q(l) + ',').join('\n') + '\n};');
o.push('static const int kDefaultN[119] = {' + W.DEFAULT_N.map(v => v == null ? -1 : v).join(', ') + '};');
o.push('// Z -> melting K, boiling K, flag (s sublimes, p needs pressure, e estimated, a allotropes), density g/cm³; NAN = not known');
o.push('struct TempData { double melt, boil; char flag; double density; };');
o.push('static const TempData kTempD[119] = {{NAN, NAN, 0, NAN},\n' + W.TEMPD.slice(1).map(t => `    {${num(t[0])}, ${num(t[1])}, ${t[2] ? q(t[2]).replace(/"/g, "'") : 0}, ${num(t[3])}},`).join('\n') + '\n};');
o.push('struct Category { const char* name; int hue; };');
o.push('static const Category kCats[] = {' + W.CATS.map(c => `{${q(c[0])}, ${c[1]}}`).join(', ') + '};');
o.push('static const int kCatOf[119] = {-1, ' + Array.from({length: 118}, (_, i) => W.CATS.findIndex(c => c[2].includes(i + 1))).join(', ') + '};');
o.push('struct Famous { int Z, N; const char* why; };');
o.push('static const Famous kFamous[] = {' + W.FAMOUS.map(f => `{${f[0]}, ${f[1]}, ${q(f[2])}}`).join(', ') + '};');
o.push('struct BetaKnown { int Z, A; double be2, sign; };   // measured B(E2; 0+ -> 2+) in e² b², and the sign of the deformation');
o.push('static const BetaKnown kBetaKnown[] = {' + Object.entries(W.BETA_KNOWN).map(([k, v]) => `{${k.split(',')[0]}, ${k.split(',')[1]}, ${v[0]}, ${v[1]}}`).join(', ') + '};');
o.push('// "Where you meet it" for each element (nullptr: the web uses a category fallback)');
o.push('static const char* const kEveryday[119] = {nullptr,\n' + Array.from({length: 118}, (_, i) => '    ' + (W.EVERYDAY[i + 1] ? q(W.EVERYDAY[i + 1]) : 'nullptr') + ',').join('\n') + '\n};');
o.push('static const int kMagicN[] = {' + W.MAGIC_N.join(', ') + '};');
o.push('static const int kMagicZ[] = {' + W.MAGIC_Z.join(', ') + '};');
fs.writeFileSync(path.join(__dirname, '../src/atom/atom_data.inc'), o.join('\n') + '\n');
console.log('wrote atom_data.inc');
