#!/usr/bin/env python3
# 0.49: builds src/orbit/voyager_data.inc from the saved JPL Horizons tables in data/jpl/voyager/ (see its README.txt). Run from native/.
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
out = ["// Generated by native/tools/make_voyager_data.py from data/jpl/voyager/ (JPL Horizons, read 11 Nov 2026). Do not edit by hand.",
       "// The Voyagers on 1 January 00:00 TDB of every year 1990 to 2026: Julian date (TDB) and x, y, z in au, heliocentric, ecliptic J2000."]
for n in (1, 2):
    path = os.path.join(root, "data", "jpl", "voyager", f"horizons_voyager{n}_1990_2026_yearly.txt")
    text = open(path, encoding="utf-8").read()
    body = text.split("$$SOE")[1].split("$$EOE")[0]
    rows = []
    for line in body.strip().splitlines():
        f = [s.strip() for s in line.split(",")]
        rows.append((f[0], f[2], f[3], f[4]))
    assert len(rows) == 37, len(rows)
    out.append(f"static const VoyagerRow kVoyager{n}[{len(rows)}] = {{")
    for jd, x, y, z in rows:
        out.append(f"    {{{jd}, {x}, {y}, {z}}},")
    out.append("};")
open(os.path.join(root, "src", "orbit", "voyager_data.inc"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote src/orbit/voyager_data.inc")
