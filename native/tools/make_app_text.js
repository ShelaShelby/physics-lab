// Copies the web app's app-wide texts and data out of index.html into native/src/app/app_text.inc,
// by running the web's own code (tests/reference/app_web.js) and reading what it builds:
// Settings, themes, achievements, the history, About, the language list and the "Did you know?" facts.
// Run from the repository root:   node native/tools/make_app_text.js
'use strict';
const fs = require('fs'), path = require('path');
const {loadAppWeb} = require('../tests/reference/app_web.js');
const {serialize} = require('../tests/reference/fake_dom.js');
const q = s => JSON.stringify(String(s));
const o = ['// Generated by native/tools/make_app_text.js from index.html. Do not edit by hand.'];
const r = loadAppWeb(), A = r.A;
const walk = (e, f) => { if (!e || typeof e !== 'object') return; f(e); (e.children || []).forEach(c => walk(c, f)); };
const all = (root, cls) => { const out = []; walk(root, e => { if ((' ' + e.className + ' ').includes(' ' + cls + ' ')) out.push(e); }); return out; };

// ---- Settings: the headings, the options, the notes ----
r.els('settingsBtn').onclick();
const S = r.ctx.lastBox;
o.push(`static const char* const kSettingsTitle = ${q(r.ctx.lastTitle)};`);
o.push(`static const char* const kSetH[] = {${all(S, 'setH').map(e => q(e.innerHTML)).join(', ')}};`);
const ps = S.children.filter(e => e.tagName === 'p').map(e => e.innerHTML);
o.push(`static const char* const kSizeNote = ${q(ps[0])};`);
o.push(`static const char* const kSizeSample = ${q(ps[1])};`);
o.push(`static const char* const kUnitsNote = ${q(ps[2])};`);
o.push(`static const char* const kMotionNote = ${q(ps[3])};`);
o.push('struct SizeOpt { const char* key; const char* name; double factor; };');
o.push(`static const SizeOpt kTextSizes[] = {${A.TEXT_SIZES.map(([k, n]) => `{${q(k)}, ${q(n)}, ${r.ctx.PL_SIZES[k]}}`).join(', ')}};`);
o.push('struct FontOpt { const char* key; const char* name; };');
o.push(`static const FontOpt kFonts[] = {${Object.keys(r.ctx.PL_FONTS).map(k => `{${q(k)}, ${q(r.ctx.PL_FONTS[k][0])}}`).join(', ')}};`);
const grids = all(S, 'setGrid');
const nameSub = b => /<span class="nm">(.*?)<small>(.*?)<\/small><\/span>/.exec(b.innerHTML);
const opts = g => g.children.map(b => { const m = nameSub(b); return `{${q(m[1])}, ${q(m[2])}}`; });
o.push('struct NameSub { const char* name; const char* sub; };');
o.push(`static const NameSub kUnitOpts[] = {${opts(grids[0]).join(', ')}};`);
o.push(`static const NameSub kMotionOpts[] = {${opts(grids[1]).join(', ')}};   // auto, on (reduced), off (full)`);
const rows = all(S, 'setRow').map(nameSub);
o.push(`static const NameSub kResetRow = {${q(rows[0][1])}, ${q(rows[0][2])}};`);
o.push(`static const NameSub kUnlockRow = {${q(rows[1][1])}, ${q(rows[1][2])}};`);

// The reset pop-ups and the "Unlock everything" line, for every count of secret themes (0–2) and achievements
// (0–5): the web's own template literals from index.html, filled in with the web's own plural rule
const plural = (n, w) => n + ' ' + w + (n === 1 ? '' : 's');
const tmpl = (re, args) => { const src = re.exec(r.html)[1]; return new Function(...args, 'plural', 'return `' + src + '`;'); };
const nothing = /show\('(<div class="gi">ℹ️<\/div><h2>Nothing to reset<\/h2>.*?)'\);/.exec(r.html)[1];
const ask = tmpl(/show\(`(<div class="gi">⚠️<\/div><h2>Reset your progress\?<\/h2>.*?)`\);/, ['th', 'ac']);
const done = tmpl(/show\(`(<div class="gi">✅<\/div><h2>Progress reset<\/h2>.*?)`\);/, ['th', 'ac']);
const unlockLine = tmpl(/paintD\(`(✅ Unlocked .*?)`\);/, ['t', 'a']);
// check the templates against the web's real run once: 2 themes and 5 achievements unlocked
{
  const w = loadAppWeb({storage: {plUnlock: 'synthwave,monochrome', plAch: JSON.stringify(Object.fromEntries(A.PLAch.list.map(x => [x.id, 0])))}});
  w.els('settingsBtn').onclick(); all(w.ctx.lastBox, 'setRow')[0].onclick();
  const got = w.body.children.find(e => e.id === 'giftBg').innerHTML;
  if (got !== `<div id="gift" role="dialog" aria-modal="true">${ask(2, 5, plural)}</div>`) throw new Error('reset template differs from the web run');
}
const table = (name, f, comment) => {
  o.push('// ' + comment);
  o.push(`static const char* const ${name}[3][6] = {`);
  for (let t = 0; t <= 2; t++) o.push('  {' + [0, 1, 2, 3, 4, 5].map(a => q(f(t, a))).join(',\n   ') + '},');
  o.push('};');
};
o.push(`static const char* const kResetNothing = ${q(nothing)};`);
table('kResetAsk', (t, a) => ask(t, a, plural), '[secret themes][achievements] -> the "Reset your progress?" pop-up');
table('kResetDone', (t, a) => done(t, a, plural), '[secret themes][achievements] -> the "Progress reset" pop-up');
table('kUnlockMsg', (t, a) => unlockLine(t, a, plural), '[themes unlocked][achievements unlocked] -> the line after "Unlock everything"');
o.push(`static const char* const kResetDoneLine = ${q(/lrnEl\('p', 'lrnP setDone', '(✅ Done\..*?)'\)/.exec(r.html)[1])};`);

// ---- themes: the list, and the colours of each (the CSS at the top of index.html) ----
const vars = {};
for (const m of r.html.matchAll(/:root\[data-pl="(\w+)"\]\{([^}]*)\}/g)) {
  const v = vars[m[1]] = vars[m[1]] || {};
  for (const kv of m[2].split(';')) { const [k, val] = kv.split(':'); if (k && k.startsWith('--')) v[k.slice(2)] = val; }
}
o.push('struct ThemeDef { const char* id; const char* name; const char* sub; const char* swatchBg; const char* swatchAccent; bool secret;');
o.push('                  const char* bg; const char* fg; const char* muted; const char* card; const char* line; const char* accent; const char* onacc; bool light; };');
o.push('static const ThemeDef kThemes[] = {');
for (const [id, name, sub, bg, ac, secret] of A.THEMES) {
  const v = vars[id] || {};
  const light = id === 'auto' ? false : /color-scheme:light/.test((r.html.match(new RegExp(`:root\\[data-pl="${id}"\\]\\{[^}]*\\}`)) || [''])[0]);
  o.push(`  {${q(id)}, ${q(name)}, ${q(sub)}, ${q(bg || '')}, ${q(ac || '')}, ${!!secret}, ${q(v.bg || '')}, ${q(v.fg || '')}, ${q(v.muted || '')}, ${q(v.card || '')}, ${q(v.line || '')}, ${q(v.accent || '')}, ${q(v.onacc || '')}, ${light}},`);
}
o.push('};');
// the theme menu's locked lines (from the web's own menu, both secrets locked)
r.els('themeBtn').onclick();
const menu = r.body.children.find(e => e.id === 'themeMenu');
const locked = menu.children.filter(b => b.className === 'lock').map(b => /<small>(.*?)<\/small>/.exec(b.innerHTML)[1]);
o.push(`static const char* const kThemeLocked[] = {${locked.map(q).join(', ')}};   // synthwave, monochrome`);
o.push(`static const char* const kThemeBtnTip = ${q(/id="themeBtn" class="ver" title="([^"]*)"/.exec(r.html)[1])};`);
o.push(`static const char* const kSettingsBtnTip = ${q(/id="settingsBtn" class="ver" title="([^"]*)"/.exec(r.html)[1])};`);

// ---- achievements ----
o.push('struct AchDef { const char* id; const char* ic; const char* name; const char* how; const char* done; };');
o.push(`static const AchDef kAchievements[] = {${A.PLAch.list.map(a => `\n  {${q(a.id)}, ${q(a.ic)}, ${q(a.name)}, ${q(a.how)}, ${q(a.done)}}`).join(',')}};`);

fs.mkdirSync(path.join(__dirname, '../src/app'), {recursive: true});
fs.writeFileSync(path.join(__dirname, '../src/app/app_text.inc'), o.join('\n') + '\n');
console.log('wrote app_text.inc');
